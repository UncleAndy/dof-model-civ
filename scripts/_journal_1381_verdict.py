"""§13.81: вердикт — дописывается в объявленный раздел протокола."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"

VERDICT = """
**Вердикт (дописан после данных).**

*Источник:* все записи прошедших сессий, где есть ходы (те же 134 файла `knowledge/live_trace_*`),
поле `разбивка` — поимённый состав набора на каждом ходу. Стенд не занимался.

| событие | сколько имён |
|---|---|
| выпало из набора | **120** |
| вернулось в набор | **0** |
| появилось впервые | 263 |

**По объявленному правилу:** возвращений **не наблюдалось** — односторонность **не опровергнута**.
Записано именно так, а не «невозможно»: правило требовало хотя бы одного возвращения, и его нет ни
в одной из записей.

**Что видно в числах, кроме итога.** Выпадения сосредоточены в **длинных** партиях: 28 в
`9522_port6000`, по 14 и 13 в `9513`, 10 в `9512_port6004`, 9 и 10 в `9514` — тогда как короткие
сессии дают 0 или 1. То есть состав набора со временем только теряет имена и ничего не возвращает,
и на длинной дистанции это не единичный случай, а устойчивая картина.

**Главное ограничение, названное в протоколе заранее и подтверждённое делом.** В записи нет
состояния целиком: «выпала» означает «выпала из набора», и это может быть как вердикт
`proven_unreachable`, так и **уничтожение** сущности в игре. Различить их по одной трассе
нельзя, поэтому этот замер **не** доказывает односторонность правила — он показывает, что
возвратов не бывает **в том, что мы наблюдаем**. Утверждение о необратимости остаётся гипотезой.

**Что нужно, чтобы развести два случая (объявляется следующим шагом).** В проекте уже есть
готовый читатель вердиктов достижимости (`env.spec_graph.recoverability`, он же используется
смоуком). Если записывать вердикт по каждой сущности в ход, то «выпала по вердикту» и «выпала
из-за уничтожения» станут двумя разными числами, и односторонность станет проверяемой прямо.
Это добавление записи, решения не касающееся.
"""


def main() -> None:
    text = CAL.read_text(encoding="utf-8")
    if "возвращений **не наблюдалось**" in text:
        print("вердикт 13.81 уже дописан")
        return
    CAL.write_text(text.rstrip() + "\n" + VERDICT, encoding="utf-8")
    after = CAL.read_text(encoding="utf-8")
    print("вердикт 13.81 дописан | строк:", after.count("\n"))


main()
