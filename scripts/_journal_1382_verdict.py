from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"

VERDICT = """
**Вердикт (дописан после данных).**

*Источник:* живая сессия слот 6003, сид 9560, 12 ходов, туман, сцена `aifill = 8`, запись
`knowledge/live_trace_9560_port6003.jsonl`. Воротник перед запуском: смоук линз 92/0, проверка
набора 10/0.

| ход | сущностей | вердикты |
|---|---|---|
| 2 … 6 | 6 | `reachable` = 6 |
| 7 … 9 | 7 | `reachable` = 7 |
| 10 | 8 | `reachable` = 8 |
| 11 … 12 | 9 | `reachable` = 9 |
| 13 | 11 | `reachable` = 11 |

**Инструмент работает.** Вердикт записывается по каждой сущности и меняется вместе с набором:
6 → 11 имён за двенадцать ходов. Второй сборки не понадобилось — объекты берутся те же, что и для
индекса, поэтому цена оказалась нулевой по коду.

**По объявленному правилу:** смены вердикта **не наблюдалось** (сменивших вердикт сущностей — 0
из 12), обратного перехода `proven_unreachable` → `reachable` — тоже 0. Записано именно так:
«обратного перехода не наблюдалось».

**Главное, что удалось, — развести два случая числом.** Выпадений из набора за сессию было одно,
и оно пришлось **не** на вердикт: выпало по вердикту `proven_unreachable` — **0**, выпало при
другом вердикте или без него — **1** (`unit_121`, вердикта нет вовсе). То есть то самое различение,
которого не хватало §13.81, теперь выражено двумя разными числами, и первое наблюдение говорит:
в этой сессии выпавшая сущность ушла **не** по решению правила.

**Чего этот замер НЕ показал, и это надо сказать прямо.** За сессию `proven_unreachable` **не
встретился ни разу**: все двенадцать сущностей были `reachable`. Значит односторонность правила
здесь **не проверялась** — проверялся инструмент. Решающая сессия — та, где сущности действительно
уходят из достижимого: длинная партия, где открытие карты и потери идут вместе.

**Следующий шаг объявлен, а не сделан.** Прогнать ту же пробу по длинным партиям (150 ходов) —
но их записи вердиктов ещё не несут: поле появилось сегодня. Значит либо длинная сессия с новым
полем, либо повтор длинных прогонов. Длинные прогоны запускает владелец, поэтому шаг называется
здесь, а не запускается самовольно.
"""


def main() -> None:
    text = CAL.read_text(encoding="utf-8")
    if "Инструмент работает." in text:
        print("вердикт 13.82 уже дописан")
        return
    CAL.write_text(text.rstrip() + "\n" + VERDICT, encoding="utf-8")
    after = CAL.read_text(encoding="utf-8")
    print("вердикт 13.82 дописан | строк:", after.count("\n"))


main()
