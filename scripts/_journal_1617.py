"""13.317: как считать отправки (моя ошибка дважды) и что эталон не перепроверен."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"
TITLE = "## 13.317. Как считать отправки (моя ошибка дважды) и что эталон не перепроверен"
BODY = """## 13.317. Как считать отправки (моя ошибка дважды) и что эталон не перепроверен

### Ошибка счёта, повторившаяся дважды за заход

Считать действия по образцу надо ПРОВЕРЯЯ образец на живой строке, а не по памяти. Оба раза
ошибка меняла вывод на противоположный:

* `produce_City` оказалось **`produce_City Walls`** — пробел обрывал разбор посуды образцом
  `[A-Za-z_]+`, и я прочитал «город производит поселенцев» там, где производились стены;
* `отправляю produce_Settlers городу 121` не совпадает с образцом `отправляю city/produce_X`,
  и я получил «поселенцы не производятся ВООБЩЕ» там, где их пятнадцать.

Верные образцы для нашего следа:

```
постановки:  отправляю produce_<Имя> городу <N>      (имя может содержать пробел!)
действия:    отправляю unit/<имя> (актёр <N>)
без DoF:     [без DoF] отправляю <род>/<имя> (актёр <N>) (кандидатов N, предпочтение X)
```

Правило на будущее: перед выводом из счёта — показать одну живую строку и убедиться, что образец
её ловит. Две ошибки за заход стоили двух неверных выводов (о производстве и о расширении).

### Исправленные числа расширения (3 эпизода × 45 ходов, `dof_economic`)

| что | сколько |
|---|---|
| `produce_Settlers` отправлено | **15** (≈5 на эпизод) |
| `unit/build_city` отправлено | **9** (≈3 города на эпизод) |
| цена поселенца по его формуле | ценность ≈542 за **14 ходов** (город размера 2) |
| наши города в конце | 2, население 3 |

То есть поселенец есть, но стоит 14 ходов городского производства, и часть их не доходит до
основания. Темп расширения упирается в щиты города, а не в выбор клетки.

### Эталон НЕ перепроверен — и это блокирует цель

Цель захода — «не хуже встроенного ИИ», и число, под которое идёт вся работа, — **23 города,
население 182, счёт 152.50** (замер 3 встроенных `normal` + наш хранитель). Этот замер сделан
давно и на нынешнем стенде **не повторялся**. Проверено сейчас:

* в раннере НЕТ опции хранителя (0 решений) и нет `--aifill` — как запускалась рука B, из
  текущего кода не видно;
* чужие города в срез не попадают вовсе (0 строк из 3141 с непустыми `foreign_cities`), поэтому
  сравнить рост ИИ стенда по нашим же партиям нечем.

Значит оптимизировать дальше под «23 города» нельзя: цель — воспоминание, а не замер. Следующий
шаг — ПОДТВЕРДИТЬ эталон (найти, как запускалась рука B, либо воссоздать её: встроенные ИИ играют
сами, наш агент не решает ничего), и только потом мерить до него расстояние. Это дешевле любой
следующей правки: сейчас мы можем упорно приближаться к числу, которого на стенде нет.
"""

text = CAL.read_text(encoding="utf-8")
if TITLE in text:
    start = text.find(TITLE)
    end = text.find("\n## 13.", start + len(TITLE))
    text = (text[:start] + BODY.rstrip() + text[end:]) if end >= 0 else (text[:start] + BODY)
    print(f"Replaced {TITLE}")
else:
    text = text.rstrip() + "\n\n" + BODY
    print(f"Appended {TITLE}")
CAL.write_text(text, encoding="utf-8")
