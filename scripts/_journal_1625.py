"""13.325: прибор тоньше — 8 партий на плечо, перестановочный тест; плечи неразличимы."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"
TITLE = "## 13.325. Прибор тоньше: 8 партий на плечо и перестановочный тест — плечи неразличимы"
BODY = """## 13.325. Прибор тоньше: 8 партий на плечо и перестановочный тест — плечи неразличимы

### Что исправлено в способе судить

§13.324 судил о переносе выбора площадки по **трём** партиям на плечо и давал «9.0 против 14.3».
Этого мало: в плече без правки одна партия дала 0 очков и 0 городов (сторона погибла), и такая
партия тянет среднее куда угодно. Поставлено **по 8 длинных партий** на плечо (150 ходов, автослот,
рука `dof_economic`), разбор **по партиям**, разницу проверяет перестановочный тест.

| мера | с правкой (§13.323) | без правки (код `b35d24e^`) |
|---|---|---|
| счёт | **13.00 ± 3.12** (9…18) | **12.00 ± 5.24** (0…20) |
| города | 0.88 ± 0.33 | 1.12 ± 0.60 |
| население | 1.75 ± 1.64 | 1.88 ± 1.27 |
| построено юнитов | 6.25 ± 2.90 | 5.50 ± 4.12 |
| изучено технологий | 5.62 ± 1.41 | 4.88 ± 2.15 |
| ходов сыграно (среднее) | 147.1 | 127.8 |

Разница счёта **+1.00**, перестановочный тест на 20000 перестановок: **p ≈ 0.735**. Это
**неразличимость**, а не «лучше» и не «хуже».

### Что из этого следует

1. **Перенос выбора площадки не вредит и не помогает** в пределах этой меры. Он оставлен как
   верный исходнику (`daisettler.c:1113-1140`), и теперь это решение **не подгонка**: откат был бы
   реакцией на шум трёх партий.
2. **Прошлый вывод «хуже на 5.3» отозван** — он был получен прибором, который грубее вопроса.
   Записываю это как урок метода: три партии на недетерминированном стенде с разбросом 0…20 очков
   не решают ничего; порог различения задаёт разброс, а не желание.
3. **Разрыв с эталоном не здесь.** Обе руки дают **около одного города** за 150 ходов, тогда как
   встроенный ИИ к тому же сроку имеет ~8 городов на место. Значит дело не в том, куда идёт
   поселенец, и не в выборе клетки: дело в **производстве и росте города** — и это подтверждается
   второй раз (первый раз — случай с `units_built = 1` до правки меры; теперь он равен 5.5–6.25,
   но городов всё равно один).

### Побочно, к оснастке

Несколько партий одной командой (`--episodes 8`) на этом стенде дешевле и надёжнее, чем серия
одиночных запусков: подготовка слота дороже самой игры, а партии идут минуты. Длинные серии стали
рабочим инструментом, а не редким событием.
"""

text = CAL.read_text(encoding="utf-8")
if TITLE in text:
    start = text.find(TITLE)
    end = text.find("\n## 13.", start + len(TITLE))
    text = (text[:start] + BODY.rstrip() + text[end:]) if end >= 0 else (text[:start] + BODY)
    print(f"Replaced {TITLE}")
else:
    text = text.rstrip() + "\n\n" + BODY
    print(f"Appended {TITLE}")
