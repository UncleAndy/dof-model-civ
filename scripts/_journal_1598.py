"""13.298: цена работы считается от клетки С её улучшениями, а не от чистой основы."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"
TITLE = "## 13.298. Цена работы считается от клетки С её улучшениями, а не от чистой основы"
BODY = """## 13.298. Цена работы считается от клетки С её улучшениями, а не от чистой основы

### Что было не так

Остаток из 13.296/13.297: при выборе работы рабочего мы брали **основу** выходов по террейну (`TERRAIN_BASE_OUTPUTS`), а экстры клетки — уже построенные улучшения — отбрасывали (`terrain, _extras = tile_terrain_extras(...)`). Значит:

* выгода работы на УЖЕ улучшенной клетке считалась от чистой основы и выглядела больше, чем есть;
* работа, которая уже сделана, могла выбираться повторно.

Это не «недоделка на будущее»: прирост, посчитанный от неверной базы, — неверный прирост, и он попадал прямо в сравнение.

### Как исправлено

Экстры приходят в ТОМ ЖЕ слое карты, что и террейн, поэтому теперь выходы считаются `tile_outputs_from_rules(terrain, extras)` — основа плюс эффекты уже имеющихся улучшений (`Irrigation`, `Mine`, дорога в доле террейна). Это то же число, что и раньше, но взятое от настоящей клетки.

### Измерено

Исправление видно прямо в следе — одна и та же клетка до и после:

```
plains ()            → (1.0, 1.0, 0.0)     # голая равнина
plains ('Irrigation',) → (2.0, 1.0, 0.0)   # та же клетка, орошённая
```

Прежде оба случая давали `(1,1,0)`. Теперь цена работы считается от того, что на клетке есть.

Отчёт: `dof_economic 2 30.0 turns … Score 4.5 Errs 0` — все 30 ходов, ошибок нет. Решения по работам: `build_road` отложено в пользу `irrigation` и `mine` — как и должно быть по его числам.

### Чего я не утверждаю

Роста в этом прогоне нет, и счёт 4.5 внутри прежнего разброса — улучшения я не приписываю. Это исправление **верности** числа, а не рычаг роста: раньше сравнение шло по неверной базе, теперь по верной.
"""

text = CAL.read_text(encoding="utf-8")
if TITLE in text:
    start = text.find(TITLE)
    end = text.find("\n## 13.", start + len(TITLE))
    text = (text[:start] + BODY.rstrip() + text[end:]) if end >= 0 else (text[:start] + BODY)
    print(f"Replaced {TITLE}")
else:
    text = text.rstrip() + "\n\n" + BODY
    print(f"Appended {TITLE}")
CAL.write_text(text, encoding="utf-8")
