def main() -> None:
    text = CAL.read_text(encoding="utf-8")
    if "коробка роста измерена на стенде" in text:
        print("дополнение уже есть")
        return
    CAL.write_text(text.rstrip() + "\n" + ADD, encoding="utf-8")
    after = CAL.read_text(encoding="utf-8")
    print("дополнение записано:", "коробка роста измерена на стенде" in after,
          "| строк:", after.count("\n"))


main()
