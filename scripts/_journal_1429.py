"""§13.129: наблюдатель входит, но умирает от ожидания хода — нужен путь чтения без хода."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"

SECTION = """
### 13.129 Наблюдатель входит, но умирает от ожидания хода: путь чтения у клиента ходовой

**Что измерено.** Наблюдатель запущен **первым** (§13.128), вошёл в свежую партию, включил обзор всей
карты и начал опрос мира по часам. Через несколько минут он умер, и не от отказа, а от собственного
устройства клиента:

    civrealm.exception.exceptions.BeginTurnTimeoutException: Timeout: No begin_turn packet received from server.

Причина видна в коде: путь чтения у клиента **привязан к ходу**. `get_info_and_observation()` зовёт
`_get_info()`, который ждёт пакет начала хода; `_get_observation()` отдаёт состояние через
`turn_manager.get_observation()`. У наблюдателя ходов не бывает вовсе — он не игрок, — поэтому ходовое
ожидание для него не заканчивается никогда, и первый же таймаут его снимает.

**Что из этого следует.**

1. Наблюдатель как «всевидящая линейка» **технически возможен** (вход есть, обзор включается), но требует
   **отдельного пути чтения мимо ходового замка**: читать не «наблюдение хода», а собственные кэши клиента,
   которые мир и так ему присылает (игроки, города, юниты). Это отдельная работа, а не правка одной строки;
   пока она не сделана, наблюдателя для замера использовать нельзя — он умирает на первом ходу ожидания.
2. Заранее объявляю, что **эту работу нельзя путать с итогом опыта**: у нас уже есть честная линейка по
   всем игрокам (записи всех сторон + серверный счёт, который видим всем и потому туманом не страдает), и
   она достаточна для объявленного (§13.125) чтения. Наблюдатель — это **усиление данных** (вся карта
   целиком), а не условие опыта.
3. Владельцу, который просил собрать максимум данных: путь к максимуму — либо этот путь чтения мимо
   ходового замка, либо объединение наблюдений всех сторон (они все наши, значит вместе знают больше, чем
   каждая по одиночке). Второе доступно уже сейчас и включено в записи.

**Состояние приборов на момент записи.** Идёт третья партия на шесть наших мест (слот 6303, `aifill 0`,
`minp 6`, 20 ходов) — запущена без наблюдателя, поэтому её записи будут как в первых двух: счёт и индекс
по каждой стороне. Вывод клиентов буферизуется (в логах до закрытия пусто) — знать это надо, иначе
«идёт» и «умерло» выглядят одинаково (§13.128).
"""


def main() -> None:
    text = CAL.read_text(encoding="utf-8")
    if "### 13.129 Наблюдатель входит" in text:
        print("раздел 13.129 уже записан")
    else:
        CAL.write_text(text.rstrip() + "\n" + SECTION.rstrip() + "\n", encoding="utf-8")
        print("раздел 13.129 записан | знаков:", len(CAL.read_text(encoding="utf-8")))


main()
