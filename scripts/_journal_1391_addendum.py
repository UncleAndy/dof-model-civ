"""§13.91 дополнение: опровергнутое ожидание П2 и его разбор (после данных)."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"

ADD = """

**Дополнение по П2 (после прогона, опровержение названо, а не сглажено).** Объявленное в §13.91
ожидание «при hr 0.6 критерий свидетеля НЕ выполняется» **опровергнуто первым же прогоном**: сумма
`DoF(после) + delta` вышла -0.046, то есть критерий выполняется. Разбор арифметики: при этой линзе
`DoF(hr) = c*hr + w*s_future*hr^2` — квадрат по hr есть следствие двойного входа здоровья (пункт 7.1
владельца, оставлено как есть), поэтому критерий `DoF(после) <= DoF(до)/2` равносилен `hr <= ~0.707`,
а не `hr <= 0.5`, как я объявил. Порог переобъявлен ДО новых данных (hr 0.8 — нет, hr 0.7 — да) и
проверен отдельно. Ожидание было моим; измерение его не подтвердило, и оно остаётся неверным.

**Вторая ошибка, найденная до данных (в моём же первом коде).** Величина сначала считалась без
множителя меры (базовый DoF без `x hr`), то есть не по мере §13.89; исправлено до прогонов. И ещё
одна, найденная ПРОГОНОМ, а не чтением: событие называет сущность (`unit_5`), а сырое наблюдение —
ключ мира (`5`), из-за чего первый прогон дал ноль актов при наблюдённом нападающем. Обе правки —
в `strike_acts`; ни одна не меняет объявленную формулу величины, только способ её достать.
"""


def main() -> None:
    text = CAL.read_text(encoding="utf-8")
    if "Дополнение по П2 (после прогона" in text:
        print("дополнение уже записано")
        return
    CAL.write_text(text.rstrip() + "\n" + ADD, encoding="utf-8")
    print("дополнение к §13.91 записано | строк:", CAL.read_text(encoding="utf-8").count("\n"))


main()
