SECTION = """
### 13.99. Порядок индексов карты: замер, моя ошибка и настоящая ошибка проекта

**Повод.** Скилл стенда (`dof-model-civ`) утверждает: слои карты индексируются `[x][y]`. Комментарии
проекта (`env/spec_threat.py`, `env/spec_collapse_candidates.py`) утверждают обратное: `[y][x]`. Мой
сегодняшний зонд читал `[y][x]`. Три разных утверждения значат, что решает замер, а не память.

**Замер, якорь — свои.** Координаты наших юнитов и города публикуются в секциях `unit`/`city`, а слой
`map.unit_owner` обязан показать там наш id (0). Результат: чтение `[x][y]` даёт 0 для **4 юнитов из 4**,
чтение `[y][x]` — **0 из 4**. Порядок — **`[x][y]`**; скилл стенда прав, мой зонд и комментарии проекта нет.

**Настоящая ошибка проекта, измеренная поведением.** `env/spec_collapse_candidates._cell` делает
`layer[yi][xi]`, а `env.spec_threat.foreign_units_from_map` перечисляет строки как `y`. На том же захвате
функция проекта возвращает **255** на клетках наших четырёх юнитов, где истина **0** («нашего юнита
нет»), и **0** на зеркальных клетках (41,25), (42,24), (42,25), (43,26), где истина 255 («наш юнит стоит
в отражённом месте»). Различаются **8 клеток из 2704** — поэтому симптом почти невидим, и ошибка дожила
до сегодняшнего дня.

**Моя ошибка, названная рядом.** `scripts/_probe_map_specs.py` читал карту `[y][x]` и потому напечатал
окрестность города транспонированной, а я по ней записал «окрестность не разведана». По верному порядку
окрестность (радиус 2) разведана на **22 клетки из 25**, в ней видны местности 2, 6, 8, 11, 12 и
дополнения 29 и 11. Вывод §13.97 (виды 14 и 22 не судятся) **сохраняется, но причина другая**: мир в этом
захвате не публикует справочник имён местностей и дополнений (упоминаний `river`, `grassland`, `hill` в
срезе — ноль), поэтому значение 13 нельзя назвать рекой иначе как догадкой, а догадка запрещена.

**Объявлено ДО правки.** Привожу чтение слоёв к измеренному порядку `[x][y]` — в `_cell` и в
перечислении `foreign_units_from_map` (включая порядок возвращаемой тройки), а комментарии-утверждения
меняю на измеренные. Ожидаемый эффект: на этом захвате значения меняются ровно на **8 названных
клетках**; чужих юнитов на карте в этом срезе нет, поэтому канал чужих не меняется. Коэффициентов и
порогов не вводится ни одного: это исправление ЧТЕНИЯ, а не модели.
"""


