"""13.304: найдена причина обрыва — город умирал от голода; перенесена годность управляющего."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"
TITLE = "## 13.304. Город умирал от голода: перенесено условие годности его управляющего"
BODY = """## 13.304. Город умирал от голода: перенесено условие годности его управляющего

### Что нашлось при разборе обрыва

`dof_expansionist` обрывался на 23.5 ходах из 45 **трижды подряд** — это повтор, а не разброс.
Разбор состояния показал сообщение среды прямым текстом:

```
Famine destroys Nyar'yana-Mar entirely.    (ход 2)
```

и следом `сущ=0 (город 0, юнит 0) … разбит=True` — **обнуление**. В действиях того хода стоит
`city_unwork_9_-2_0`: мы сняли единственного горожанина в специалиста, еда стала нулевой, и город
умер от голода. То есть обрыв — не про войну и не про простой: **наш же ход по клетке убивал город**.

### Почему это было возможно

Мы взяли из его управляющего городом **веса** (`city_tile_value`: еда 30, щиты 17, торговля 18),
но не взяли **годность** — а у него это условие стоит ДО сравнения выгоды, `common/aicore/cm.c:623`:

```c
output_type_iterate(stat_index) {
    fitness.weighted += surplus[stat_index] * parameter->factor[stat_index];
    if (surplus[stat_index] < parameter->minimal_surplus[stat_index]) {
      fitness.sufficient = FALSE;          /* вариант отбрасывается ЦЕЛИКОМ */
    }
} output_type_iterate_end;
```

По весам клетка со щитами и без еды **выигрывает**: `(1,3,0)` шахта холма = 104.5 против
`(2,0,0)` луга = 75. Поэтому расстановка по одним весам ставит жителя туда, где город не прокормится.

### Перенесено

Вариант клетки, при котором город голодает, отбрасывается целиком, до сравнения выгоды: новое
сальдо = текущий излишек ∓ еда клетки, и при `< 0` вариант не рассматривается. Это же правило
закрывает и второй источник голода — снятие последнего кормящего горожанина.

### Измерено

Срабатывание видно прямо в следе:

```
[клетка-годность] город 121: отброшено голодных вариантов 1 — {'city_unwork_6_-1_1': -1.0} (при излишке 1)
[клетка-правила] молчит: город 121: все варианты клетки голодные — хода нет
```

Три партии по 30 ходов: **30.0 из 30 в каждой**, `Score 4.7`, ошибок 0. **Голода нет ни одного**
(прежний обрыв на 23.5 ходах — это как раз гибель города). К концу прогона 2 города, один
размера 2 с излишком 1. За прогон годность сработала **121 раз**.

### Что это значит для захода

Второй раз подряд причина оказалась **половиной его правила**: сначала цена поселенца без запрета
разбирать город (13.301/13.302), теперь веса расстановки без годности. Обе «половины» по
отдельности не просто бесполезны — они **вредны**: первая давала 25 поселенцев и вымирание,
вторая давала голодную смерть города. Это прямое подтверждение требования владельца переносить
логику целиком.
"""

text = CAL.read_text(encoding="utf-8")
if TITLE in text:
    start = text.find(TITLE)
    end = text.find("\n## 13.", start + len(TITLE))
    text = (text[:start] + BODY.rstrip() + text[end:]) if end >= 0 else (text[:start] + BODY)
    print(f"Replaced {TITLE}")
else:
    text = text.rstrip() + "\n\n" + BODY
    print(f"Appended {TITLE}")
CAL.write_text(text, encoding="utf-8")
