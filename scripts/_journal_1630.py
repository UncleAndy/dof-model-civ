"""13.330: A/B на 8 партиях — рост и производство сдвинулись, счёт нет."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"
TITLE = ("## 13.330. A/B на 8 партиях (150 ходов): население выросло вдвое, счёт не сдвинулся")
BODY = """## 13.330. A/B на 8 партиях (150 ходов): население выросло вдвое, счёт не сдвинулся

### Что сравнивалось

Плечи различаются ОДНОЙ правкой §13.329 (требования управляющему сервера: излишек еды ≥ 1 его
числами, `cityturn.c:313-360`, перенесены в начало `act` и включены по умолчанию). По 8 партий
в плече, 150 ходов, одна рука (`dof_economic`),перестановочный тест (20 000 перестановок, сид 7).

| мера | до правки | после правки | разница | p |
|---|---|---|---|---|
| население | 1.75 ± 1.64 | **3.38 ± 1.58** | +1.62 | 0.100 |
| города | 0.88 ± 0.33 | 1.38 ± 0.70 | +0.50 | 0.254 |
| построено юнитов | 6.25 ± 2.90 | 8.75 ± 4.63 | +2.50 | 0.278 |
| **счёт** | 13.00 ± 3.12 | 14.00 ± 6.20 | +1.00 | **0.748** |
| технологии | 5.62 ± 1.41 | 5.12 ± 2.42 | −0.50 | 0.732 |

Разброс счёта в плече с правкой вдвое больше (6.20 против 3.12): одна партия дала 22 очка (3 города),
одна — 5. При таком разбросе 8 партий не различают и разницу в 1 очко.

### Что доказано, а что нет

- **Доказано механизмом, а не счётом:** требования доходят (0 отправок → **53** за 40 ходов) и
  излишек еды стал **1** вместо 0 (замер на 40 ходах: «рост через» 19 → 11 → 3, размер 1 → 2).
  Это прямой замер замочка, который был назван в §13.328.
- **Не доказано счётом:** улучшение счёта. Тенденция есть у населения (p = 0.10), но при 8 партиях
  это ещё не результат. Утверждать «стало лучше» по счёту было бы подгонкой.

### Наблюдение из плеча после правки

Партии, где города было больше одного (`cities=2`, `cities=3`), дали и больший счёт (22 и 21 против
5-14 у одногородных): `land_area` 29–40 тыс. против 13–33 тыс. То есть **расширение остаётся
главным рычагом**, и оно по-прежнему редко: 1.38 города в среднем, тогда как встроенный ИИ на
критерии держит ~8 на место (эталон, который ещё не перепроверен, §13.317).

### Ошибка способа, которую здесь же исправляю

Фоновые серии в этом окружении **убиваются** (первая попытка на 8 партий: exit −1 через 2 минуты,
успела одна партия). Надёжный способ — передний план порциями по 2–3 партии (одна партия ~2 минуты,
предел вызова 600 с), результат каждого плеча — в свой файл, чтобы разбор шёл по файлам, а не по
памяти.
"""

text = CAL.read_text(encoding="utf-8")
if TITLE in text:
    start = text.find(TITLE)
    end = text.find("\n## 13.", start + len(TITLE))
    text = (text[:start] + BODY.rstrip() + text[end:]) if end >= 0 else (text[:start] + BODY)
    print(f"Replaced {TITLE}")
else:
    text = text.rstrip() + "\n\n" + BODY
    print(f"Appended {TITLE}")
CAL.write_text(text, encoding="utf-8")
