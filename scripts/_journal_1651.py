"""13.354: сколько решений за ход и два опровергнутых объяснения отставания."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"
TITLE = "## 13.354."
BODY = """## 13.354. Сколько на самом деле решений за ход, и два опровергнутых объяснения

Прежние следы печатали только ЧАСТЬ путей: ранний возврат правила поселенца уходит мимо печати
отправки, поэтому «12 отправок за 12 ходов» читалось как «одно действие в ход». Число решений
теперь считает сам цикл (`decisions_this_turn`, `used_actors`) и печатает под `DOF_CHOICE_DEBUG=1`.

**Замер (`ch6`, 14 ходов):** решений за ход **3–5**, задействовано актёров столько же — то есть
каждый доступный юнит действует один раз за ход. **Опровергнуто** объяснение «мы действуем один
раз за ход»: это был артефакт следа.

**Опровергнуто и «шаг не исполняется»** (прибор `DOF_FORCE_STEP=goto_4`, §13.351): юнит идёт
+1 клетка за ход двенадцать ходов подряд.

**И опровергнуто «цена юнитных действий 0.0» как причина отказа от основания:** прибор
`DOF_CHOICE_DEBUG=1` печатает меню мира, вывод генератора и список после наших правил. Факт
(ход 1): мир предлагает **2** основания, генератор оставляет **1**, после наших правил остаётся
**1** — и когда основание в списке, его предпочтение **3.0** (выше работы клетки 2.0 и хода 1.0),
и оно отправляется. То есть цена работает, и основание проигрывает только тогда, когда его в
списке нет вовсе.

Что видно по меню мира: за один ход мир отдаёт 5–6 юнитных актёров и 40–64 годных действия,
и по мере использования актёров меню СЖИМАЕТСЯ в одном и том же ходу (60 → 48 → 36 → 21 → 10).
Наши решения расходуются по одному на актёра, и это верно.

**Вывод замера:** ни цикл, ни канал, ни цена основания не объясняют разрыв. Разрыв — в СОДЕРЖАНИИ
решений за длинную игру (города стоят на 1, пока у встроенного ИИ их ~8). Следующий шаг —
мерить не «сколько действий», а ЧТО они делают: доля шагов поселенца, заканчивающихся основанием,
за 150 ходов, и сравнение с тем, что делает его правило на той же карте.

Новые приборы (все под ключами, норматив не меняют): `DOF_CHOICE_DEBUG=1` — `[ход-вход]`
(меню мира на каждом вызове), `[выбор-ход]` (мир / генератор / после правил + верх списка с
числами), `[решений-за-ход]`; в следе отправки появился номер хода.
"""

text = CAL.read_text(encoding="utf-8")
if TITLE in text:
    start = text.find(TITLE)
    text = text[:start] + BODY
else:
    text = text.rstrip() + "\n\n" + BODY
CAL.write_text(text, encoding="utf-8")
print(f"journal updated: {TITLE}")
