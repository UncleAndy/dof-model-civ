"""13.305: спасение голодающего города перенесено, но первый город всё ещё гибнет на 2-м ходу."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"
TITLE = "## 13.305. Спасение голодающего города перенесено; первый город всё ещё гибнет на 2-м ходу"
BODY = """## 13.305. Спасение голодающего города перенесено; первый город всё ещё гибнет на 2-м ходу

### Порядок «годность ПЕРЕД выгодой» перенесён до конца

В 13.304 годность была добавлена как **отсев** голодных вариантов. Этого мало: наш отбор брал
только ходы с **положительным** выигрышем по весам (`if gain <= 0: break`), поэтому ход, который
убирает голод и не даёт выигрыша, отбрасывался — и город продолжал голодать. У него порядок
обратный: `cm.c:623` сначала требует годности по всем статьям, и только среди годных берёт
взвешенную выгоду.

Добавлен `_city_tile_rescue`: если излишек еды отрицательный, выбирается ход, **улучшающий
сальдо**, независимо от выигрыша — и уходит раньше обычного отбора.

### Измерено

```
[клетка-спасение] город 121: city_work_2_0_-1 — излишек -1 → 2 (годность ПЕРЕД выгодой, cm.c:623)
[клетка-спасение] город 121: city_work_10_0_-2 — излишек -1 → 1
```

16 срабатываний за прогон; голодный город вытащен в плюс. Прогон 2 плеча × 2 партии × 45 ходов:
годность сработала, ошибок 0.

### Чего НЕ достигнуто — и это главное

**Первый город всё ещё гибнет.** В логе перед итогом:

```
[состояние 2] свои города=[] … сообщения='Famine destroys Lobamba entirely. Year: 3950 BCE'
[состояние 3] сущ=0 … разбит=True        ← мы разбиты на 3-м ходу
```

То есть город, основанный на 1-м ходу, умирает от голода на 2-м, и игрок выбывает.
`dof_economic` из-за этого даёт 23.5 хода из 45 — прежний обрыв `dof_expansionist` **перешёл на
другое плечо**, а не исчез. Голодных наблюдений 6 за прогон.

Спасение срабатывает **после** того, как голод возник; если предложение хода не содержит работы
на клетку с едой (или город основан там, где её нет в радиусе), спасать нечем.

### Причина, которая теперь называется точно

Основание города у нас выбирается его `ai_want` плюс его флаги голода (`starved_food`), но,
видимо, **флаг голода площадки не мешает выбору** — либо сервер ставит первого горожанина сам,
и город голодает до нашего первого хода. Это надо проверить прямо, а не догадкой: в картине мира
поле `starved_food` есть, значит проверяется оно или нет — это ровно тот же вопрос «половины
правила», что и дважды выше.

Признак на 2 партии — не вывод. Но обрыв на 3-м ходу виден в срезе прямым текстом, это не разброс.
"""

text = CAL.read_text(encoding="utf-8")
if TITLE in text:
    start = text.find(TITLE)
    end = text.find("\n## 13.", start + len(TITLE))
    text = (text[:start] + BODY.rstrip() + text[end:]) if end >= 0 else (text[:start] + BODY)
    print(f"Replaced {TITLE}")
else:
    text = text.rstrip() + "\n\n" + BODY
    print(f"Appended {TITLE}")
CAL.write_text(text, encoding="utf-8")
