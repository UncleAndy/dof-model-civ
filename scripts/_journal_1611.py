"""13.311: подключение выбора технологии — правило не срабатывает, и это замер, а не поломка."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"
TITLE = "## 13.311. Выбор технологии подключён — и не срабатывает: в стенде технологии не из чего выбирать"
BODY = """## 13.311. Выбор технологии подключён — и не срабатывает: в стенде технологии не из чего выбирать

### Что сделано

`tech.py` был найден неподключённым (13.310). Подключён его `ai_choose_tech` (`daitech.c`):
технология выбирается по наибольшему хотению, а хотение — прирост оценки НАШИХ городов от
открываемых ею построек, умноженный на ЕГО коэффициент `× 14/8`.

Добавлено в сам модуль переноса:

* `best_of(values)` — argmax СТРОГИМ сравнением: при равенстве побеждает первая встреченная,
  как у него (`if (tech_want[a] > best)`); порядок задаёт мир, переставлять его нельзя;
* `keep_best_tech(...)` — оставить в семье технологии одну лучшую, прочие роды действий не
  трогать; при полном отсутствии данных семья возвращается нетронутой.

Подключение стоит в теле `_apply_common_rules` — общей функции, которую зовут ОБА пути
(это уже пятый случай, когда правило вне общего тела оказывалось неработающим).

### Измерено: правило не срабатывает, и вот почему

След поставлен так, чтобы «не сработало» отличалось от «нечего решать»: печатать, если в одном
решении названо **две и более** технологий.

```
[технология] … — строк в следе: 0   (прогон 14 ходов, затем 40 ходов)
```

Ноль. Мир предлагает технологию **по одной на решение** (`research_tech_<текущая>` и
`set_tech_goal_<текущая>` — обе про одну и ту же). Разные имена в прежних следах
(`Alphabet`, `Advanced Flight`, `Amphibious Warfare`) — это разные ХОДЫ, а не выбор внутри хода.

Значит его `ai_choose_tech` в этом стенде выбирать не из чего: правило остаётся УСЛОВНЫМ и
сработает только если мир предложит несколько технологий сразу (другой набор правил, другой ход).

### Чего НЕ утверждаю

Счёт в контрольном прогоне 40 ходов поднялся 6.0 → 7.0, но **приписывать это подключению
нельзя**: правило за прогон не сработало ни разу (след пуст). Разница — разброс стенда, а не
следствие правки. Записываю это затем, чтобы замер не превратился в «доказательство» на
следующем заходе.

### Что осталось неподключённым

Производство города: `city_want.building_want_now` (отображение записи мира) и контрфакт
`base_want` (`daicity.c:1495`) поверх уже подключённой `effects.improvement_value`. Это
единственное известное неподключённое место переноса, и оно же — последний названный разрыв с
эталоном (23 города против 2–4).
"""

text = CAL.read_text(encoding="utf-8")
if TITLE in text:
    start = text.find(TITLE)
    end = text.find("\n## 13.", start + len(TITLE))
    text = (text[:start] + BODY.rstrip() + text[end:]) if end >= 0 else (text[:start] + BODY)
    print(f"Replaced {TITLE}")
else:
    text = text.rstrip() + "\n\n" + BODY
    print(f"Appended {TITLE}")
CAL.write_text(text, encoding="utf-8")
