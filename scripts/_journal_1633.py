"""13.333: состав сторон в одной партии — где именно разрыв (население ×48, технологии ∞)."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"
TITLE = ("## 13.333. Состав сторон в одной партии: разрыв назван по статьям, а не «в десять раз»")
BODY = """## 13.333. Состав сторон в одной партии: разрыв назван по статьям, а не «в десять раз»

### Прибор

Мир публикует состав **по каждой** стороне (`evaluate_game` отдаёт категории по `player_id`), и
это печатается в конце партии (`[состав сторон] <имя> (id N): ...`). Разбор — `scripts/_sides_table.py`
(читает лог, печатает таблицу «мы против ИИ»). Сравнение идёт ВНУТРИ одной партии, поэтому не
зависит от случайной карты — то, чего не хватало отдельным плечам (§13.330).

### Замер (партия `ref4`, 150 ходов, одна и та же карта)

| статья | мы | встроенный ИИ (среднее 3 сторон) | разброс ИИ | отношение |
|---|---|---|---|---|
| **счёт** | **2** | 131.3 | 117…149 | ×65.7 |
| **население** | **1** | 48.3 | 46…53 | **×48.3** |
| **технологий** | **0** | 35.3 | 33…38 | **×∞** |
| золото | 30 | 674.7 | 111…1427 | ×22.5 |
| заселённая земля | 3000 | 45333 | 40000…49000 | ×15.1 |
| города | 1 | 7.7 | 5…10 | ×7.7 |
| вся земля (включая разведанную) | 27000 | 200667 | 143000…248000 | ×7.4 |
| построено юнитов | 10 | 46 | 17…63 | ×4.6 |
| военных юнитов | 7 | 8 | 4…10 | ×1.1 |
| производство | 0 | 44.3 | 31…54 | ×∞ |

### Что это меняет в порядке работ

1. **Население ×48** — главная статья, и она в НАШЕМ городе выглядит как «город не вырос вовсе»
   (население 1 за 150 ходов). Прежние замеры показывали рост до 3 после правки §13.329, значит
   рост не закреплён: одна партия растёт, другая стоит. Это первое, что нужно объяснить замером.
2. **Технологии 0 против 35** — наука не идёт вовсе. Выбор технологии у нас перенесён
   (`brain/ai_default/tech.py`), но в списке незакрытого записан как «не подключён в реальности:
   мир предлагает по одной технологии на решение — 0 срабатываний». Теперь у этого есть цена в
   счёте, а не только запись в журнале.
3. **Военных юнитов поровну (7 против 8)** — а построено в 4.6 раза меньше, то есть у ИИ военные
   строятся и гибнут/используются, у нас — копятся. Это НЕ узкое место; узкое место — рост и наука.

### Оговорка

Партия одна (`ref4`). Таблица — не «средний результат», а состав одной игры наряду с четырьмя
замерами счёта (§13.332: мы 4…19 против 63…179 у ИИ). Для средних нужны ещё партии, но порядок
работ от партии не зависит: население и наука отстают на порядки, военные — нет.
"""

text = CAL.read_text(encoding="utf-8")
if TITLE in text:
    start = text.find(TITLE)
    end = text.find("\n## 13.", start + len(TITLE))
    text = (text[:start] + BODY.rstrip() + text[end:]) if end >= 0 else (text[:start] + BODY)
    print(f"Replaced {TITLE}")
else:
    text = text.rstrip() + "\n\n" + BODY
    print(f"Appended {TITLE}")
CAL.write_text(text, encoding="utf-8")
