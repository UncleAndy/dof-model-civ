"""13.362: как сделать, чтобы агент видел всю карту — исчерпаны настройки стенда, найден источник."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"
TITLE = "## 13.362."
BODY = """## 13.362. «Чтобы агент видел всю карту»: настройки стенда исчерпаны замером, найден верный источник

**Почему у встроенного ИИ карта есть, а у нас нет.** Его код читает не наблюдение, а состояние
сервера: `parameter.omniscience = !has_handicap(pplayer, H_MAP)` (`server/unittools.c:531`,
`server/advisors/autoworkers.c:464,842,1090`, `advbuilding.c:94`) — то есть маршруты он строит по
ВСЕЙ карте, пометки `H_MAP` у него нет. Наш агент живёт на наблюдении клиента, а клиент видит
только обзор (§13.361): замер `вне обзора 4035, известно-невидимо 0, видно 21`.

**Что уже испробовано и чем кончилось** (всё замером по слою `status`):

1. `/set fogofwar disabled` из клиента в игре — отказ: настройка правил после старта не меняется
   (`settings.c:3417-3425`).
2. `set fogofwar disabled` во все четыре сценария стенда (`/docker/publite2/pubscript_*.serv`,
   копии `.dof-backup`) + перезапуск — значение в сейве стало `FALSE`, а карта как была под
   туманом: клетки уже созданы, а `plrtile->seen_count[V_MAIN] = !game.server.fogofwar_old`
   (`server/maphand.c:1348`) выставляется ПРИ СОЗДАНИИ клеток, и позже его никто не пересчитывает
   (правка на лету `srv_main.c:1244` срабатывает, только если значение изменилось в ходе игры,
   а для настроек правил это запрещено).
3. `lock fogofwar` рядом с настройкой (чтобы смена правил клиента не возвращала туман) — то же.
4. Правка клиента: `/set fogofwar disabled` сразу после `/rulesetdir` (наша копия `civrealm/`) —
   значение в сейве `FALSE,«Changed»`, карта по-прежнему `4035` вне обзора.
5. Редакторский путь «снять туман игроку» — штатный, для игры в процессе: посылки
   `PACKET_EDIT_MODE = 190` (`BOOL state`) и `PACKET_EDIT_TOGGLE_FOGOFWAR = 199` (`PLAYER player`)
   по `common/networking/packets.def:2204/2214`, обработчик `server/edithand.c:1312`
   (`disable_fog_of_war_player`). Обе посылки уходят от нашего клиента (видно в следе:
   `[карта-открыта] послал {'pid': 190, 'state': True}`, `{'pid': 199, 'player': 0}`), но
   состояние клеток не меняется: обработчику нужен уровень доступа `ALLOW_HACK` у соединения
   (`edithand.c:1498`) и режим редактора сервера, а веб-клиент стенда такого уровня не получает.

**Вывод.** Настройками стенда наша ВИДИМОСТЬ не открывается: карта в партии создаётся раньше, чем
любая наша настройка успевает подействовать, а редакторский путь закрыт уровнем доступа веб-клиента.

**Правильный источник — тот же, что у встроенного ИИ: состояние сервера.** Мир (террейн всей
карты) лежит в сохранённой игре сервера: `/save` из клиента → файл
`/var/lib/tomcat10/webapps/data/savegames/<имя>/<имя>_T<ход>_<дата>.sav.xz` внутри стенда,
в нём таблица клеток. Это НЕ догадка и не выдумка: это данные того же мира, что читает его
`omniscience`, и по решению владельца от 2026-10-12 характеристики мира (`§13.3xx`: «цена — это
характеристика мира; её достаточно узнать один раз и сохранить в картину мира») берутся из
источника. Так наш агент получит ту же картину, что у него, без изменения самой игры.

**Что оставлено в стенде** (всё обратимо):
`set fogofwar disabled` + `lock fogofwar` в четырёх `pubscript_*.serv` (копии
`.dof-backup` рядом — откат копированием), правка клиента под флагом `DOF_KEEP_RULESET`
(по умолчанию смена правил не отправляется) и `DOF_REVEAL_MAP` (по умолчанию посылки редактора
шлются). Ни то, ни другое карту не открывает — но и не мешает.
"""

text = CAL.read_text(encoding="utf-8")
