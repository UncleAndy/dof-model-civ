SECTION = """
### 13.128 В партию, созданную на N мест, N+1-го не пускают: наблюдатель обязан входить первым

**Что измерено.** Наблюдателя попробовали пустить в **уже идущую** нашу игру (шесть игроков, слот 6302,
ход 10 из 20). Мир ответил прямо:

    RuntimeError: You are logged in as 'myagent' connected to no player. There is no room for new players.
    You may increase the maximum player number or change the username to match an existing player.

То есть в партию, созданную на шесть мест, седьмого клиента не пускают — ни игроком, ни наблюдателем.
Подсказка мира «войти под именем существующего игрока» для нас **запрещена**: второй вход под тем же
именем выбивает из-за стола нашего же агента (тот, кто сидит за этим игроком), и опыт остался бы без
одной из сторон. Это не осторожность, а цена ошибки: измерение снесло бы предмет измерения.

**Вывод, объявляемый как правило.** Наблюдатель входит **вместе со всеми и раньше всех** — в свежую
партию, до старта. Порядок такой: сначала наблюдатель (входит, включает обзор всей карты, его место
освобождается, потому что наблюдатель не игрок), затем N наших агентов; партия начинается, когда
подключились все N игроков (`minp N`), и наблюдатель видит мир с первого хода. Владелец получает то, что
требовал: результат по **всем игрокам и всей карте**, а не по куску, который видит под туманом каждая
сторона.

**Ещё один измеренный урок (стоил видимости пробы).** Вывод пробы, направленный в файл, буферизуется:
пока процесс жив, в логе пусто, и «проба ничего не делает» выглядит одинаково с «проба работает молча».
Клиенты запускать с небуферизованным выводом (`-u`), иначе снимок виден только после закрытия пробы.

**И урок об обёртках.** Прогон, запущенный обёрткой (`&` + `wait`), теряет плечи, если его снимает обрыв
сессии: шесть клиентов предыдущего прогона (слот 6302, ход 10/20) умерли вместе с обёрткой, и их записи
не сохранились — 10 ходов игры пропали. Долгие прогоны надо запускать так, чтобы процесс жил сам
(отдельная сессия процесса), а не потому, что жива оболочка.
"""


