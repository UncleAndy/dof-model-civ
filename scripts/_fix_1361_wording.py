"""Снять из §13.61 неточность: «за ход у юнита одно действие» — неверно (за ход доступны ВСЕ действия
актора, это установлено ранее). Правильная причина потери — юнит, уведённый в разведку, не делает то,
что приносило городу чистый прирост щитов, а мера города растёт только от такого прироста.
"""
from pathlib import Path

DOC = Path("/home/hermes/projects/AI/DOF-MODEL-CIV/drafts/DOF_CALIBRATION.md")
OLD = """нашего опыта это подтверждает с другой стороны: за 150
ходов шаг разведки не приносит счёту ничего, а стоит — потому что за ход у юнита **одно** действие, и
шаг разведки его занимает. Движение в нашей постановке не «дополнительная» деятельность, а **замена**
производительной."""
NEW = """нашего опыта это подтверждает с другой стороны: за 150
ходов шаг разведки счёту не приносит ничего, а стоит — потому что юнит, уведённый в разведку, не делает
того, что давало городу **чистый прирост щитов** (а мера города растёт только от такого прироста).
Движение в нашей постановке не «дополнительная» деятельность, а **замена** производительной. Оговорка
про темп: за ход актору доступны все его действия, поэтому ограничение «один шаг за ход» — это
требование мира (иначе он не успевает, `server_timeout_handle`), а не свойство игры."""
text = DOC.read_text(encoding="utf-8")
if OLD not in text:
    print("фраза не найдена — возможно, уже исправлена")
else:
    DOC.write_text(text.replace(OLD, NEW, 1), encoding="utf-8")
    print("исправлено, байт:", DOC.stat().st_size)
print("── контроль: сколько раз встречается спорная фраза ──")
print(DOC.read_text(encoding="utf-8").count("за ход у юнита **одно** действие"))