"""§13.81: протокол — обратим ли набор счёта (мера односторонности вердиктов достижимости)."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"

SECTION = """
### 13.81. Обратим ли набор счёта: протокол (объявлен до данных)

**Вопрос.** Давний долг: вердикт недостижимости `proven_unreachable` назван **односторонним** —
сущность, выброшенная этим вердиктом из `calc(S)`, не возвращается. §13.80 дал важное: с
действительным наблюдением наш набор измерения **совпадает** с `calc(S)` ядра (6 = 6, 8 = 8),
значит по трассе видно, как состав набора меняется от хода к ходу. Здесь это и измеряется:
**возвращается ли когда-нибудь сущность, однажды выпавшая из набора.**

**Где смотрим.** Записи прошедших сессий (`knowledge/live_trace_*.jsonl`), поле `разбивка` —
поимённый состав измеренных сущностей на каждом ходу. Стенд не занимается, ничего не меняется.

**Как считаем.** По каждой записи идём по ходам и следим за множеством имён сущностей. Считаем
три события: **выпала** (имя было и пропало), **вернулась** (имя пропало и появилось снова),
**новая** (имени раньше не было). Печатаем число каждого вида и примеры имён.

**Правило решения (объявлено ДО данных).**

* Если есть хотя бы одно **возвращение**, односторонность **опровергнута** на этих данных: набор
  обратим, и долг закрывается числом.
* Если возвращений **нет** — односторонность **не опровергнута**, и это записывается именно так:
  «не наблюдалось возвращений», а не «невозможно». Тогда утверждение о необратимости остаётся
  гипотезой, требующей отдельного замера там, где сущность снова становится достижимой.

**Ограничение, названное заранее.** В записи нет состояния целиком, только **измеренные**
сущности. Поэтому «выпала» означает «выпала из набора», и это может быть как вердикт
`proven_unreachable`, так и **уничтожение** сущности в игре. Различить их по одной трассе
нельзя, и в вердикте это будет сказано, а не сглажено.
"""


def main() -> None:
    text = CAL.read_text(encoding="utf-8")
    if "13.81." in text:
        print("раздел 13.81 уже есть")
        return
    CAL.write_text(text.rstrip() + "\n" + SECTION, encoding="utf-8")
    after = CAL.read_text(encoding="utf-8")
    print("13.81 (протокол) записан:", "13.81." in after, "| строк:", after.count("\n"))


main()
