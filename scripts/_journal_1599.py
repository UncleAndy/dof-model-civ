"""13.299: на длине эталона (45 ходов) город всё ещё размера 1 — разрыв в расширении."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"
TITLE = "## 13.299. На длине эталона (45 ходов) город всё ещё размера 1 — разрыв в расширении"
BODY = """## 13.299. На длине эталона (45 ходов) город всё ещё размера 1 — разрыв в расширении

Замер на ТОЙ ЖЕ длине, что у эталона (45 ходов), после всех правок захода:

| рука | ходы | счёт | ошибок |
|---|---|---|---|
| `dof_economic` | **23.5 из 45** | 1.5 | 0 |
| `dof_expansionist` | 45.0 из 45 | 5.5 | 0 |

Размер города на последнем срезе — **1** (излишек еды 1), население до 4, то есть городов 3–4.

Эталон для сравнения: 3 встроенных ИИ `normal` — **23 города, население 182, счёт 152.50**. Разрыв не сократился.

### Что это значит

Перенос решений (выбор работы рабочим, расстановка жителя, оценка клетки, дороги) работает и ошибок не даёт, но **роста и расширения он не даёт** — и по числам видно, что дело не в клетке: излишек еды положительный, горожанин ставится осознанно, а размер остаётся 1. Узкое место — **расширение** (основание новых городов), а не обустройство существующего.

Ранее уже было измерено (§13.279): поселенец стоит 40 ходов по щитам, желание основать город (9.2) дисконтируется γ⁴⁰ до 1.60 и **проигрывает** `Barracks` (3.71 за 30 ход). То есть основание новых городов проигрывает постройке в существующем — и это ровно то, что мешает расширению. Эта причина не устранена переносом работы клетки: она в решении ГОРОДА о производстве.

Отдельно стоит проверить, не мешают ли друг другу два управляющих расстановкой жителей: серверный (`cma_enabled`, мы шлём ему веса food=20, pid 257) и наш перенесённый выбор. Это тот же класс, что «два решателя на один вопрос», и он уже дважды оказывался ошибкой (§13.204).

Роста нет. Приписывать переносу нечего.
"""

text = CAL.read_text(encoding="utf-8")
if TITLE in text:
    start = text.find(TITLE)
    end = text.find("\n## 13.", start + len(TITLE))
    text = (text[:start] + BODY.rstrip() + text[end:]) if end >= 0 else (text[:start] + BODY)
    print(f"Replaced {TITLE}")
else:
    text = text.rstrip() + "\n\n" + BODY
    print(f"Appended {TITLE}")
CAL.write_text(text, encoding="utf-8")
