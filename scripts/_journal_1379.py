"""§13.79: протокол — набор расчёта и индекс ядра рядом с нашим (объявлен до данных)."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"

SECTION = """
### 13.79. Набор расчёта и индекс ядра рядом с нашим: протокол (объявлен до данных)

**Вопрос.** Наш индекс считается суммой по **всем измеренным** сущностям, а ядро — по **набору
расчёта** `calc(S)` (§4.2), из которого выкинуто только доказанно недостижимое. Если счёты
расходятся, то число, по которому принимается решение, — не число ядра, и это надо знать, а не
предполагать.

**Что объявлено заранее.** В запись хода добавляются три поля, решения не касаясь: `в_расчёте`
(размер набора расчёта), `индекс_ядра` (индекс ядра по этому набору) и `причина_набора`
(названное состояние по §13.66 — пустой набор обязан говорить, что 0.0 значит «считать нечего»).
Поле `индекс`, по которому принимается решение, **не меняется**.

**Оговорка о наборе.** Набор считается с `ctx=None`, то есть как **предохранительный** (§4.2:
без наблюдения `calc` — предохранительный надкласс). Значит записанный набор — самый широкий из
возможных, и набор, по которому шло решение, может быть уже. Это названо здесь, чтобы запись не
читалась как «тот самый набор решения».

**Правило решения (объявлено ДО данных).**

* Если на живом прогоне `индекс` и `индекс_ядра` **совпадают**, вопрос расхождения закрыт для
  этой сессии — и закрыт числом, а не рассуждением.
* Если **расходятся**, разница публикуется как **наблюдение** с числами. Поведение при этом НЕ
  меняется: правка пути решения была бы сменой линейки после данных и требует решения владельца.

**Чего протокол НЕ делает.** Не меняет ядро (ядро — линейка), не меняет индекс решения, не вводит
коэффициентов, не запускает кампании. Наборы, выброшенные ядром как `proven_unreachable`,
остаются на своём месте: здесь только видимость.
"""


def main() -> None:
    text = CAL.read_text(encoding="utf-8")
    if "13.79." in text:
        print("раздел 13.79 уже есть")
        return
    CAL.write_text(text.rstrip() + "\n" + SECTION, encoding="utf-8")
    after = CAL.read_text(encoding="utf-8")
    print("13.79 (протокол) записан:", "13.79." in after, "| строк:", after.count("\n"))


main()
