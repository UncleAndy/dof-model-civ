"""13.315: замер перед сменой меры — расстановки совпадают, менять пока нечего."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"
TITLE = "## 13.315. Замер перед сменой меры: его управляющий и наша мера дают ОДНУ расстановку"
BODY = """## 13.315. Замер перед сменой меры: его управляющий и наша мера дают ОДНУ расстановку

### Зачем замер

В 13.314 найдено, что расстановку жителей он делает управляющим (`cm.c`), а наш путь меряет
клетку мерой рабочего (`infracache.c`). Прямой вывод «значит, надо переписать путь» был бы
догадкой: две меры могут давать один и тот же выбор, и тогда правка — чистая потеря. Поэтому
сначала счёт, потом правка.

### Что сделано для счёта

* в срез мира добавлено поле города `рабочие_клетки` — еда/щиты/торговля каждой клетки радиуса
  по НАШЕМУ читателю карты (`env.site_eval.tile_output`), то есть по тем же числам, что видит
  живой путь. Прежнее `окно_клеток` для этого не годится: порядок чисел в нём не подтверждён, а
  еда и щиты там рядом — ошибка в порядке исказила бы весь замер;
* `scripts/_cm_vs_worker_measure.py` — счёт без правок: обе расстановки берутся как лучшие
  «размер города» клетки, одна по мере рабочего (`values.city_tile_value`), другая по его
  взвешенной сумме (`city_manager.score` с его весом пищи и порогами), и сравниваются итоговые
  излишек еды и щиты.

### Результат

```
город 128: наблюдений 11 с пригодными числами
  мера рабочего 1/2  ↔  управляющий 1/2   — 10 наблюдений
  мера рабочего 1/3  ↔  управляющий 2/3   —  1 наблюдение
расстановки РАЗЛИЧАЮТСЯ в 1 из 11
```

То есть на доступных числах обе меры дают **одну и ту же** расстановку: спорная разница в одном
наблюдении из одиннадцати, и она в пользу управляющего (на единицу больше излишка еды).

### Вывод, который из этого следует

**Смена меры пока не обоснована замером.** Наблюдённый застой городов (излишек 0) этой разницей
не объясняется: если бы дело было в мере, расстановки расходились бы постоянно, а не один раз из
одиннадцати. Значит причина застоя — в другом месте, и искать её надо там, а не переписывать путь
расстановки «потому что у него иначе».

Оговорка о силе: пригодных наблюдений мало (11 у одного города), потому что поле `рабочие_клетки`
появилось только что. Прежде чем делать вывод о мере вообще, надо набрать наблюдений на нескольких
городах и прогонах — замер уже готов и повторяется одной командой.

Что остаётся непроверенным подозреваемым: у него при неудаче порогов есть ПОВТОР с ослабленными
порогами (`cityturn.c:430-434`), у нас его нет — если ни одна расстановка не проходит, город
может остаться без выбора вовсе. Это и проверяется следующим.
"""

text = CAL.read_text(encoding="utf-8")
if TITLE in text:
    start = text.find(TITLE)
    end = text.find("\n## 13.", start + len(TITLE))
    text = (text[:start] + BODY.rstrip() + text[end:]) if end >= 0 else (text[:start] + BODY)
    print(f"Replaced {TITLE}")
else:
    text = text.rstrip() + "\n\n" + BODY
    print(f"Appended {TITLE}")
CAL.write_text(text, encoding="utf-8")
