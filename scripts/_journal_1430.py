"""§13.130: линейка по всем игрокам найдена — стенд сам пишет очки всех игроков по ходам."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"

SECTION = """
### 13.130 Линейка по всем игрокам уже есть: стенд сам пишет очки всех игроков по ходам

**Что найдено (и это закрывает главную часть задачи владельца).** По каждой нашей партии стенд сам
складывает каталог `game_scores/<время>-<слот>/` с двумя файлами:

* `players.json` — кто за кем сидел (номер игрока → имя);
* `evaluations.json` — **по каждому игроку ряд по ходам** и по **16 категориям**: `score`, `population`,
  `economics`, `production`, `cities`, `researched_techs`, `military_units`, `wonders`, `research_speed`,
  `land_area`, `settled_area`, `gold`, `units_built`, **`units_killed`**, **`units_lost`**, `units_used`.

Источник — собственный счёт игры на стороне сервера: клиент запрашивает у мира свод очков
(`civrealm/envs/freeciv_base_env.py` → `civ_controller.request_scorelog()` → `game_ctrl.get_game_scores`).
Значит линейка **внешняя по отношению к любому агенту** и **одинаковая во всех играх** — ровно то, что
требовал владелец: «счёт должен вычисляться по всем игрокам по всей карте», а не по тому, что сторона
успела разглядеть под туманом.

**Сверка двух независимых каналов сошлась.** Наша партия шести мест (слот 6301) по своду стенда:
`score` на последнем ходу = **9, 7, 7, 7, 5, 4** — в точности те числа, которые были посчитаны мной из
записей сторон (`scripts/seats_report.py`, §13.126). Два разных пути дали одно и то же, значит линейка не
выдумана и не зависит от нашего кода.

**Заодно закрылся вопрос о войне.** В тех же данных есть прямые признаки нападений — `units_killed` и
`units_lost`. В прошедших партиях там **нули у всех** (убито 0, потеряно 0), то есть по объявленному
правилу «любое нападение = война» войны не было вовсе: дешёвый агент не воюет. Это подтверждает вывод
§13.126 уже с серверной стороны, а не с наших записей.

**Побочная, но важная деталь для будущего замера.** Ряды содержат 26 значений при 25 ходах (стартовое
плюс по одному на ход), `land_area` идёт в тысячах клеток, `units_killed`/`units_lost` различают, кто
нападал, а кто терял. Для расчётов надо брать последнее значение как итог, а ряд — как ход событий.

**Оснастка.** Добавлен `scripts/game_scores_report.py`: печатает по партии таблицу всех игроков, объявленные
варианты (сумма, среднее, разброс) по счёту и по ключевым категориям, и вердикт о войне по объявленному
правилу. Наблюдатель как «всевидящая линейка» после этой находки нужен только для индекса DoF по всей
карте, а для счёта уже не нужен вовсе (§13.129).
"""


def main() -> None:
    text = CAL.read_text(encoding="utf-8")
    if "### 13.130 Линейка по всем игрокам уже есть" in text:
        print("раздел 13.130 уже записан")
    else:
        CAL.write_text(text.rstrip() + "\n" + SECTION.rstrip() + "\n", encoding="utf-8")
        print("раздел 13.130 записан | знаков:", len(CAL.read_text(encoding="utf-8")))


main()
