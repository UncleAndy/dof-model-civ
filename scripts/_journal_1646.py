"""13.346: реестр клинов молча резал поселенца — 100 ходов воинов серверным умолчанием."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"
TITLE = "## 13.346."
BODY = """## 13.346. Поселенец молча резался реестром клинов: 100 ходов очередь клепала воинов

### Что нашлось

Выбор производства упирался в строку лога **«маски дали 3 типов, ни один не оценён — постановку
не меняем»**: маска МИРА содержала `Settlers`, но цены у него не было. При этом строк
`[желание] Settlers` за партию было **НОЛЬ** — то есть правило желания даже не звалось.

Причина — предохранитель клинов. В цикле стоял голый `is_wedged("city", "produce_Settlers")`:

| имя | отказов в реестре | успехов | `is_wedged` | `is_wedged_family` |
|---|---|---|---|---|
| `city/produce_Settlers` | 6 | **9** | **True** (резать) | False (играть) |

Голый `is_wedged` считает **отказы и не смотрит успехи** (`_active_failures`: `pending >= 2`).
Шесть отказов накопились в партиях, кончившихся по таймауту, — и имя, которое **девять раз
сработало**, было отрезано молча (в логе не было ни строки о пропуске).

### Чем это стоило

`growA` (150 ходов, дамп): поселенцы строились до 50-го хода, дальше — **ни одного за 100 ходов**,
поселенцев в игре 0, юнитов 13→20 (все воины — серверное умолчание `choose_build_target`), а к
134-му ходу городов стало **1 вместо 2**: город потерян.

### Исправление

Резать имя можно только по **подтверждённому** отказу: `is_wedged_family` (ни разу не вышло) плюс
`is_wedged_here` (именно в этой клетке) — то же правило, что уже записано в скилле для
`unit/build_city` (3 отказа при 37 успехах резались им в новых клетках). Пропуск теперь
**печатается**: молчание больше не скрывает отсев.

### Замер (`wedge1`, 2×40 ходов, тот же стенд)

| что | до (§13.343-13.345) | после |
|---|---|---|
| строк `[желание] Settlers` | **0** | **20** (желание 533.7 — «его площадка (40,23): total 651.9, ходов 1») |
| приказов о производстве | 6 за 80 ходов, из них 2 военных | **9 `produce_Settlers`** + 1 `Barracks` |
| военных юнитов | 10 и 13 | **0** и 7 |

Это не доказательство паритета (одна партия ничего не доказывает), но **механизм** доказан
следом: раньше правило желания не звалось вовсе, теперь зовётся и даёт 533.7.

**Следующий шаг:** длинная партия (150 ходов, ≥3 порции) с исправленным реестром — мерить города,
население, технологии против встроенного ИИ; и посмотреть, не режется ли тем же голым правилом
ещё что-нибудь (по реестру: `city/city_work` — 53 отказа при 439 успехах, `unit/plant` — 26 при 0).
"""

