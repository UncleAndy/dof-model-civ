"""§13.82: протокол — вердикт достижимости по сущности в ход (развести два случая выпадения)."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"

SECTION = """
### 13.82. Вердикт достижимости по сущности в ход: протокол (объявлен до данных)

**Вопрос.** §13.81 измерил выпадения из набора счёта (120 имён, возвратов 0), но не смог
различить два разных случая: сущность выпала **вердиктом** `proven_unreachable` или её
**уничтожили** в игре. Без этого различия односторонность правила остаётся гипотезой. Здесь она
становится проверяемой: в запись хода добавляется **вердикт по каждой сущности**.

**Почему это почти ничего не стоит.** Контекст наблюдения и состояние **уже** строятся в отчётном
пути (правка §13.80), и читатель вердиктов в проекте есть: `env.spec_graph.recoverability`
(им пользуется смоук). Значит второй сборки не требуется — берутся те же объекты.

**Что объявлено заранее.** В запись хода добавляется поле `вердикты`: имя сущности → вердикт
(`reachable` / `undetermined` / `proven_unreachable`) и краткая причина. Поле `индекс` решения не
меняется, коэффициентов не вводится, ядро не трогается.

**Правило решения (объявлено ДО данных).**

* Если в сессии найдётся сущность, у которой вердикт **сменился** с `proven_unreachable` на
  `reachable` — односторонность **опровергнута**: вердикт обратим.
* Если смены вердикта **не будет**, а выпадения из набора объяснятся вердиктом — записывается:
  «выпадение по вердикту наблюдалось, обратного перехода не наблюдалось».
* Если выпадение из набора произойдёт **без** вердикта `proven_unreachable`, это будет означать,
  что причина — уничтожение, и два случая разведены числом.

**Чего протокол НЕ делает.** Не меняет решение, не спорит с ядром и не объявляет необратимость
доказанной при отсутствии обратного перехода: отсутствие наблюдения — не доказательство.
"""


def main() -> None:
    text = CAL.read_text(encoding="utf-8")
    if "13.82." in text:
        print("раздел 13.82 уже есть")
        return
    CAL.write_text(text.rstrip() + "\n" + SECTION, encoding="utf-8")
    after = CAL.read_text(encoding="utf-8")
    print("13.82 (протокол) записан:", "13.82." in after, "| строк:", after.count("\n"))


main()
