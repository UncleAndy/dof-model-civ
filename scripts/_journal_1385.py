SECTION = """
### 13.85. Первое живое нападение: канал коллапса на данных, а не на синтетике

**Почему сейчас.** Канал наблюдения нападения проверялся только на синтетике (смоук I39) и на
живой съёмке, где нападений **не было** (I38). Длинная партия §13.82 (сид 9570, 150 ходов) дала
**одно** наблюдённое нападение — первый живой случай. Разбор либо снимает долг «разбор нападений
на живых данных», либо называет его точнее.

**Правило, прочитанное ДО объявления ожиданий.** Свидетелем (§4.2) считается акт, приводящий
**считаемую** сущность к известному нулю: `collapse_acts` берёт акт, у которого
`DoF(X) + Δ ≤ 0` для `X` из набора счёта (`brain/spec/world_graph.py:536–548`). В нашем графе
эффекты актов объявлены в `env/config.py:760–768` и все **неотрицательны** (`production` 1.0,
`terrain` 1.0, остальные 0.0). Следствие: **ни один акт нашего графа свидетелем быть не может**,
поэтому метка источника коллапса не подтверждается, и §4.2 оставляет помеченного в наборе счёта.

**Объявлено до чтения данных** (источник — та же запись, что и в §13.82,
`knowledge/live_trace_9570_port6003.jsonl`):

1. В записи ровно **одно** событие с `attacked: true`.
2. В его ходу названо, что потеряно или ранено (наши потери), и — если чужой был виден — кому
   приписано нападение (`marked`). Вслепую виновный не назначается: проверено на синтетике,
   ожидается и здесь.
3. Признак держится объявленный срок (20 ходов): владелец остаётся помеченным и в следующих
   ходах записи, и снимается по истечении срока.
4. Помеченный владелец появляется в канале `кандидаты_коллапса` в ходу нападения и остаётся в
   нём в пределах срока.
5. §4.2: помеченный источник коллапса **не покидает** набор счёта — свидетеля в нашем графе
   быть не может (см. правило выше). Это ожидание объявляется как **подтверждение чтения**:
   если владелец остался в счёте, чтение верно; если он из счёта выбыл, то у нас есть акт с
   отрицательным эффектом, которого я не вижу, и это надо разбирать как расхождение.
6. Что **не** проверяется: качество решения; вердикты по жертвам (жертвы — не наши сущности,
   их DoF мы не измеряем, в счёте их нет by construction — та же причина, по которой §13.82 не
   увидел ни одного выпадения по вердикту).

**Форма отчёта:** число по каждому пункту; отдельно — что подтвердилось, что нет, и что из этого
следует для счёта. Долг, если он подтвердится, называется явно: «разрушительные акты не
объявлены — метка источника коллапса неподтверждаема, агрессор остаётся в счёте».
"""


