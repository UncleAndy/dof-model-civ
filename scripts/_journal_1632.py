"""13.332: эталон перепроверен на своём стенде — мир публикует счёт каждой стороны."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"
TITLE = ("## 13.332. Эталон перепроверен на СВОЁМ стенде: 14 против 63/127/179 в одной партии")
BODY = """## 13.332. Эталон перепроверен на СВОЁМ стенде: 14 против 63/127/179 в одной партии

### Что было заблокировано

«Эталон не перепроверен» (в списке незакрытого с §13.317): число «23 города / население 182 /
**счёт 152.50**» получено давним прогоном на другом скрипте (`arm_b_ai_only.py`, `aifill 5`), а в
нынешнем раннере ни хранителя, ни `--aifill` нет, чужие города под туманом в срез не попадают.
Все выводы о разрыве опирались на неподтверждённое число.

### Что найдено (открывает замер)

Мир публикует **счёт каждой стороны**, а не только наш:

- `obs["player"]` — записи всех игроков, с именами (`[состав] сторона видит игроков: [...]`,
  в наших партиях всегда 4 стороны: мы и три встроенных ИИ);
- `env.evaluate_game()` отдаёт категории **по каждому** `player_id`, а не только по нашему.

Достаточно было прочитать последний срез по каждой стороне — и эталон получается **в той же
партии, на той же карте, с теми же настройками**, без чужого скрипта и без «23 городов» по слухам.

### Замер (одна партия, 150 ходов, `dof_economic`, рука без DoF)

| сторона | счёт |
|---|---|
| **мы** (`dof_economic`) | **14** |
| встроенный ИИ (Milton Cato, id 1) | **127** |
| встроенный ИИ (Miguel Primo de Rivera, id 2) | **63** |
| встроенный ИИ (Mustapha Khaznadar, id 3) | **179** |

Среднее встроенных в этой партии — **123**. Наш счёт 14.

### Вывод

**Разрыв реален и подтверждён собственным замером**, а не чужим числом: порядок величины совпал
(эталон 152.50 против 63–179 здесь). Значит «мы в разы хуже» перестаёт быть утверждением на
непроверенной основе — и одновременно **это готовый прибор**: дальше каждое улучшение можно
мерить против встроенного ИИ в ТОЙ ЖЕ партии, а не в отдельном плече с другим стартом и другой
картой. Это снимает и прежнюю оговорку о разбросе: сравнение внутри одной партии не зависит от
случайной карты.

### Как воспроизвести

```
DOF_PLAYERS_DEBUG=1 <раннер> ... --episodes 1 --turns 150 --timeout 7200
```
В конце партии печатается `[счёт сторон] <имя> (id N) = <счёт>` по каждой стороне. Замер серии
из нескольких партий запущен отдельно (`ref3`, 3 партии).
"""

text = CAL.read_text(encoding="utf-8")
if TITLE in text:
    start = text.find(TITLE)
    end = text.find("\n## 13.", start + len(TITLE))
    text = (text[:start] + BODY.rstrip() + text[end:]) if end >= 0 else (text[:start] + BODY)
    print(f"Replaced {TITLE}")
else:
    text = text.rstrip() + "\n\n" + BODY
    print(f"Appended {TITLE}")
CAL.write_text(text, encoding="utf-8")
