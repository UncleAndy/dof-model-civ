"""§13.78: протокол замера «отзывается ли счёт мира на основание города и на рост» (до данных).

Источник — уже прошедшие партии, стенд не занимается. Вердикт дописывается в тот же раздел.
"""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"

SECTION = """
### 13.78. Отзывается ли счёт мира на основание города и на рост: протокол (объявлен до данных)

**Вопрос.** Критерии владельца читают результат по счёту мира и требуют предпочитать больше
городов и крупнее. Пока это принималось как намерение: §13.77 показал, что по 13 партиям число
городов счёт не объясняет. Здесь проверяется узкое: отзывается ли счёт **в тот самый ход**, когда
город основан или вырос.

**Где смотрим.** Записи прошедших прогонов (`knowledge/live_trace_952*.jsonl`,
`knowledge/live_trace_9530_port6003.jsonl`). Стенд не занимается. Сцена: `aifill = 8`; плечи
различаются настройками, поэтому приписывать различие настройкам нельзя.

**Как считаем — только из публикуемого миром.** По каждой записи идём по ходам и берём счёт
(`счёт_мира`) и состав городов с размерами (`city_output`). Событие — ход, в котором число городов
выросло (**основание**) или размер какого-то города вырос (**рост**). Для события берём изменение
счёта за этот ход. Контроль — изменения счёта на всех прочих ходах той же выборки.

**Правило решения (объявлено ДО данных).** Связь **установлена**, если событий каждого вида не
меньше трёх и медиана изменения счёта на событиях этого вида строго больше медианы на прочих
ходах. Иначе — **«связь не установлена»**, и это тоже результат.

**Чего протокол НЕ делает.** Не сравнивает плечи, не применяет порог §10.95 (это не парный опыт),
не меняет модель, не запускает прогонов. Число событий публикуется рядом с медианами.

**Вердикт дописывается в этот же раздел** после данных.
"""


def main() -> None:
    text = CAL.read_text(encoding="utf-8")
    if "13.78." in text:
        print("раздел 13.78 уже есть")
        return
    CAL.write_text(text.rstrip() + "\n" + SECTION, encoding="utf-8")
    after = CAL.read_text(encoding="utf-8")
    print("13.78 (протокол) записан:", "13.78." in after, "| строк:", after.count("\n"))


main()
