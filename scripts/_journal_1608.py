"""13.308: правило F не стояло на пути без DoF — поселенцы вливались в голодающий город."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"
TITLE = "## 13.308. Правило F не стояло на пути без DoF: поселенцы вливались в голодающий город"
BODY = """## 13.308. Правило F не стояло на пути без DoF: поселенцы вливались в голодающий город

### Что нашлось — и как это выдал собственный отчёт правила

Разбирая темп расширения, я посмотрел, куда деваются поселенцы. Оказалось: в одном прогоне
`join_city` отправлен **4 раза против одного** `build_city`. Строка следа:

```
[без DoF] отправляю unit/join_city (актёр 105) (кандидатов 4, предпочтение 0.000)
```

`предпочтение 0.000` — вливание не входит ни в один список предпочтений стратегии, то есть
проигрывает основанию (`+2`). И всё же оно уходило. При этом состояние того хода:

```
[состояние 5] свои города=[(74, 27, 2, -1)]     ← размер 2, излишек −1, город ГОЛОДАЕТ
```

То есть в голодающий город влили ещё жителя — ровно то, что правило F обязано запрещать.
Проверка собственного отчёта правила подтвердила догадку:

```
правило F (еда необратима): решений проверено 0, запрещено 0
```

**«Проверено 0»** на пути, где решений сотни. Причина: отсечение стояло НИЖЕ выбора
(`run_real_tournament.py:3551`), а выбор без DoF идёт по `descore` выше этого места и
возвращает действие раньше. Путь без DoF правило не видело **вовсе**.

Это тот же класс, что и четыре прежних случая, только теперь не «механизм не вызывается», а
«правило стоит не на том пути».

### Исправлено

Отсечение перенесено к тому списку, из которого идёт выбор (`descore`), — ДО выбора, как и
требует собственный смысл правила: иначе безопасная альтернатива (выйти и основать) даже не
рассматривается.

### Измерено (1 партия, 40 ходов, `dof_economic`)

| | до | после |
|---|---|---|
| правило F | проверено **0**, запрещено 0 | проверено **122**, запрещено **73** |
| `join_city` отправлено | 4 | **0** |
| оснований города | 1 | 2 |
| города в конце | 1 × размер 2 (излишек 0) | **2 × размер 2** |
| счёт | 4.0 | **6.0** |

По семействам запретов: `city_change_specialist` 46, `join_city` 26, `city_unwork` 1. Все 73 —
в прежнем пути, «без записи города» 0, то есть правило смотрело по факту мира, а не вслепую.

### Чего не утверждаю

Один прогон — признак, а не вывод. Но «проверено 0 → 122» и «join_city 4 → 0» — это не
разброс, это состояние правила: оно либо на пути, либо нет. И расширение до 2 городов со
вторым размером 2 — первый прогон за заход с двумя городами размера 2 на 40 ходах.
"""

text = CAL.read_text(encoding="utf-8")
if TITLE in text:
    start = text.find(TITLE)
    end = text.find("\n## 13.", start + len(TITLE))
    text = (text[:start] + BODY.rstrip() + text[end:]) if end >= 0 else (text[:start] + BODY)
    print(f"Replaced {TITLE}")
else:
    text = text.rstrip() + "\n\n" + BODY
    print(f"Appended {TITLE}")
CAL.write_text(text, encoding="utf-8")
