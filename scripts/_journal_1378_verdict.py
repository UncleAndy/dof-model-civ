"""§13.78: вердикт — дописывается в объявленный раздел протокола."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"

VERDICT = """
**Вердикт (дописан после данных).**

*Источник:* 14 записей прошедших партий (те же, что в §13.77, плюс короткая сессия на слоте 6003);
стенд не занимался. События ищутся по публикуемому миру: счёт и состав городов с размерами.

| вид события | событий | медиана изменения счёта | среднее | размах |
|---|---|---|---|---|
| основание города | **5** | **+1.0** | +1.0 | ровно +1 |
| рост города (размер вырос) | **48** | **+1.0** | +1.125 | +1 … +3 |
| прочие ходы (контроль) | 1660 | 0.0 | +0.094 | −2 … +2 |

**По объявленному правилу обе связи УСТАНОВЛЕНЫ**: событий каждого вида больше трёх, и медиана
изменения счёта на событиях (1.0) строго больше медианы на прочих ходах (0.0). Сигнал при этом
предельно чистый: **основание города дало ровно +1 во всех пяти случаях**, рост — медиану +1 при
среднем +1.125.

**Как это читать вместе с §13.77.** Оба результата согласуются и не отменяют друг друга. Счёт
мира **платит за город и за его рост в тот же ход** (+1 и +1) — то есть критерии владельца
опираются на собственную меру мира, а не на его намерение. Но **накопленный итог** партии числом
городов не объясняется (§13.77: две партии с двумя городами дали 32 и 16, а с одним городом счёт
доходил до 29): кроме городов счёт набирается и другим — это видно по контролю, где прочие ходы
дают размах от −2 до +2 при медиане 0. Проще говоря: **город приносит счёт, но счёт партии не
сводится к городам**.

**Ограничения, названные честно.** (а) Источник — сцена `aifill = 8`, плечи различаются
настройками; приписывать различие настройкам здесь нельзя, и такое приписывание не делается.
(б) Событий основания всего пять: правило требовало не меньше трёх, и оно выполнено, но пять
случаев — это пять, а не множество. (в) «Прочие ходы» — это не «ходы без счёта»: там есть и
другие источники счёта, поэтому контроль сравнивается как есть, без очистки. (г) Замер читает
**факт** изменения счёта в ход события и не утверждает причину: вырос ли счёт из-за города или
одновременно с ним — из этих данных не различить.
"""


def main() -> None:
    text = CAL.read_text(encoding="utf-8")
    if "Вердикт (дописан после данных)." in text and "13.78" in text:
        if text.count("Вердикт (дописан после данных).") > 2:
            print("вердикт 13.78 уже дописан")
            return
    CAL.write_text(text.rstrip() + "\n" + VERDICT, encoding="utf-8")
    after = CAL.read_text(encoding="utf-8")
    print("вердикт 13.78 дописан | строк:", after.count("\n"))


main()
