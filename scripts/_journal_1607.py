"""13.307: цена площадки без достижимости вредна — назначение проверяется шагом."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"
TITLE = "## 13.307. Цена площадки без достижимости вредна: поселенец стоял 11 ходов"
BODY = """## 13.307. Цена площадки без достижимости вредна: поселенец стоял 11 ходов

### Своя ошибка, пойманная следом

Первый же прогон с назначением показал в следе одно и то же одиннадцать раз подряд:

```
[поселенец] unit/113: площадка (37, 21) голодная … → иду к (38, 22) (его total 525.7), шаг goto_7
[поселенец] unit/113: площадка (37, 21) голодная … → иду к (38, 22) (его total 525.7), шаг goto_7
… 11 раз
```

Поселенец **не сдвигался**: шаг `goto_7` в (38, 22) мир отклонял (клетка недостижима — вода),
а мой выбор назначения смотрел только на ЦЕНУ площадки. Значит цена без достижимости — та же
ошибка «половины», только моя собственная: цель есть, дойти нельзя, город не основан вовсе.
Это хуже, чем прежнее поведение, когда город основывался на плохой площадке.

### Исправлено

`rank_sites` — площадки по его числам **списком**, лучшие первыми; `_founder_step` берёт
ПЕРВУЮ, к которой мир предлагает законный шаг, и только тогда идёт. Если ни к одной — не
вмешивается вовсе (лучше основать на плохой площадке, чем не основать никогда).

### Измерено (2 плеча × 2 партии × 45 ходов)

| плечо | ходы | счёт | ошибок |
|---|---|---|---|
| `dof_expansionist` | 45.0 из 45 | 5.5 | 0 |
| `dof_economic` | **45.0 из 45** | **9.0** | 0 |

* вмешательств поселенца — **0** (площадки были годные): механизм редкий, не мешает обычной игре;
* обвала нет: `разбит=True` 0, `Famine destroys` 0;
* к концу — **два города, оба размера 2, у обоих излишек +1**;
* размер 2: 130 наблюдений против 164 размера 1 — лучшая доля за заход (было 25 на 376);
* голодных наблюдений — 1 (было 4–6);
* население до 4.

### Что осталось — и это уже не про смерть, а про темп

Оснований: 7 за четыре партии (≈1.75 на партию). Эталон — 23 города, население 182, счёт 152.50.
Обрыв и голодная гибель сняты; остался **темп расширения и роста**, а не выживание. Это
следующая часть его логики (`cm.c`/`daicity.c` целиком: управляющий городом и выбор
производства), и она ещё не перенесена полностью.

Признак на 4 партии — не вывод; но 45 из 45 без обвала в обеих руках и излишек +1 у городов
размера 2 — это смена состояния, а не разброс.
"""

text = CAL.read_text(encoding="utf-8")
if TITLE in text:
    start = text.find(TITLE)
    end = text.find("\n## 13.", start + len(TITLE))
    text = (text[:start] + BODY.rstrip() + text[end:]) if end >= 0 else (text[:start] + BODY)
