"""§13.131: входу наблюдателя нужно длинное терпение; сниматель не смеет трогать чужие оболочки."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"

SECTION = """
### 13.131 Два урока: наблюдателю нужно длинное терпение, а сниматель не смеет трогать чужие оболочки

**1. Вход наблюдателя умирает на ожидании старта игры.** Первый запуск линейки наблюдателя (слот 6304,
`aifill 0`, `minp 6`) умер прямо на входе:

    BeginTurnTimeoutException: Timeout: No begin_turn packet received from server.   (в env.reset)

Причина не в наблюдателе, а в двух совпавших обстоятельствах: игра **не начинается, пока не подключатся
все N мест** (`minp 6`), а клиент по умолчанию ждёт пакет хода всего **30 секунд** (`server_timeout` в
`default_settings.yaml`). Наблюдатель входит первым, значит он и ждёт старта дольше всех — и умирает
ровно на этом ожидании, до всякого наблюдения. Лечится тем же, чем лечились прежние обрывы: дать входу
длинное терпение. В пусковой оснастке наблюдателю теперь передаются `--server_timeout 600` и
`--begin_turn_timeout 600`; проверка на живой партии запущена заново (шесть наших мест, 20 ходов).

**2. Сниматель процессов зацепил оболочки моей же сессии.** Первая версия `scripts/_stop_own_games.py`
искала имена наших скриптов **в любой командной строке** и сняла по SIGTERM оболочки собственной сессии
(`bash -c …`), в тексте которых эти имена просто упоминались. Сессия выжила (команда успела закончить
работу), но это ровно та ошибка, которой проект уже дважды платил 09.10. Правило, вписанное в скрипт:

* **нашим считается только процесс, ЗАПУЩЕННЫЙ ИНТЕРПРЕТАТОРОМ PYTHON** (проверяется первый элемент
  командной строки), и в его строке есть имя нашего скрипта;
* оболочки, где имя только упомянуто, нашими не считаются;
* дополнительно исключаются признаки самого распорядителя (`hermes-snap`, `bwrap`, `AI_AGENT`) и все
  предки текущего процесса;
* есть режим примерки `--list-only`.

Проверено примеркой: ложных целей — ноль, наши процессы — ноль (прогонов нет).

**3. Потерянная партия ничего не потеряла по существу.** У партии на слоте 6302 погибли записи сторон
(их унесло вместе с обёрткой), но **серверная часть уцелела**: стенд записал очки всех шести игроков по
ходам (21 ход, 16 категорий). Значит для замера по счёту потеря обёртки не смертельна — данные мира
живут отдельно от наших процессов. Это ещё один довод в пользу того, что линейка должна быть внешней.
"""


def main() -> None:
    text = CAL.read_text(encoding="utf-8")
    if "### 13.131 Два урока" in text:
        print("раздел 13.131 уже записан")
    else:
        CAL.write_text(text.rstrip() + "\n" + SECTION.rstrip() + "\n", encoding="utf-8")
        print("раздел 13.131 записан | знаков:", len(CAL.read_text(encoding="utf-8")))


main()
