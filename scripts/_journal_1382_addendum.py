"""§13.82: дополнение — решающая длинная партия запущена по указанию владельца."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"

ADDENDUM = """
**Дополнение (после вердикта).** Решающая длинная партия запускается по указанию владельца
(«делай в самостоятельном режиме») — то есть условие, названное в вердикте владельческим,
выполнено. **Протокол при этом не меняется**: правило решения выше остаётся тем же, поле записи
(§13.82) и проба (`scripts/_probe_verdicts.py`) не расширяются, новых величин не вводится. Сессия:
слот 6003, сид 9570, 150 ходов, туман, сцена `aifill = 8`. Правило читается по той же таблице:
смена вердикта `proven_unreachable` → `reachable` опровергает односторонность; отсутствие такой
смены записывается как «обратного перехода не наблюдалось»; выпадения из набора делятся на
«по вердикту» и «без вердикта».
"""


def main() -> None:
    text = CAL.read_text(encoding="utf-8")
    if "Дополнение (после вердикта)." in text:
        print("дополнение уже есть")
        return
    CAL.write_text(text.rstrip() + "\n" + ADDENDUM, encoding="utf-8")
    after = CAL.read_text(encoding="utf-8")
    print("дополнение записано | строк:", after.count("\n"))


main()
