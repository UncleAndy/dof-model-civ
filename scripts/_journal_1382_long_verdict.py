"""§13.82: окончательный вердикт по длинной партии — дописывается в раздел."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"

VERDICT = """
**Вердикт по длинной партии (дописан после данных).**

*Источник:* слот 6003, сид 9570, **150 ходов**, туман, сцена `aifill = 8`, запись
`knowledge/live_trace_9570_port6003.jsonl` (цепочка завершилась кодом 0; воротник перед запуском:
смоук линз 92/0, дополнение записано).

| что | число |
|---|---|
| ходов | 150 |
| вердиктов за партию | **3541 — и все `reachable`** |
| сущностей | 33 |
| смен вердикта | **0** |
| переход `proven_unreachable` → `reachable` | **0** |
| выпало из набора **по вердикту** | **0** |
| выпало из набора **без вердикта** | **5** |
| набор расчёта | 6 → 28 |
| индекс | −3.8212 → −18.7897 (совпадает с индексом ядра на каждом ходу) |
| нападений за партию | 1 |

**По объявленному правилу.** Смены вердикта не наблюдалось, обратного перехода — тоже. Записано
именно так: «обратного перехода не наблюдалось».

**Главное, что выяснилось: в этой сцене вопрос не встаёт.** За полтораста ходов, с 33 сущностями и
одним наблюдённым нападением, вердикт `proven_unreachable` **не появился ни разу** — все 3541
вердикта были `reachable`. Причина видна в самой записи, у каждого вердикта стоит причина:
«DoF(X | h) > 0: the trivial path satisfies the condition (§4.9)» — пока сущность может остаться
как есть, её достижимость не обнуляется. Значит односторонность правила **здесь не проверяется**, и
это не «правило в порядке», а «испытание не состоялось»: сущности, выживание которой невозможно
**по построению**, в обычной партии не встречается.

**Разведение двух случаев при этом работает.** Из пяти выпадений партии **все пять** оказались
выпадениями **без** вердикта, и ни одного — по вердикту. То есть то, что §13.81 не мог различить,
теперь различается числом, и на длинной партии различение подтвердилось: выпавшие сущности уходили
**не** по решению правила.

**Что объявляется следующим шагом (не сделано).** Чтобы односторонность стала проверяемой, нужна
сцена, где сущность **обречена по построению** — тогда у вердикта появляется повод сработать, и
вопрос «возвращается ли выброшенное» станет измеримым. Это конструирование сцены, а не прогон, и
оно требует решения владельца: какие условия считать обречённостью.

**Ограничения.** Одна партия, один сид, один слот, `aifill = 8`, туман. Нападение за партию одно,
поэтому «под нападением» здесь наблюдено ровно один раз. Индекс ядра совпадал с нашим на каждом
ходу — это то же, что проверено в §13.80, но теперь на 150 ходах, а не на шести.
"""


def main() -> None:
    text = CAL.read_text(encoding="utf-8")
    if "Вердикт по длинной партии (дописан после данных)." in text:
        print("вердикт длинной партии уже дописан")
        return
    CAL.write_text(text.rstrip() + "\n" + VERDICT, encoding="utf-8")
    after = CAL.read_text(encoding="utf-8")
    print("вердикт длинной партии дописан | строк:", after.count("\n"))


main()
