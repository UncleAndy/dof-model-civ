"""§13.118: предел 1800 с снял два ИГРАВШИХ плеча; измеренный темп стенда; предел переобъявлен."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"

SECTION = """
### 13.118 Жёсткий предел 1800 с снял два ИГРАВШИХ плеча; предел переобъявлен по измеренному темпу

**Измерено на паре 9221 (сид 9221, слоты 6000 и 6001, 150 ходов, сцена 4, терпение 120 с).** Оба плеча
получили партию и играли:

| плечо | слот | ходов | счёт | код | снято | трасса |
|---|---|---|---|---|---|---|
| A | 6000 | **76** | 9.0 | 143 | `stalled` на 1800.8 с | 9 539 220 байт |
| B | 6001 | **90** | 9.0 | 143 | `stalled` на 1800.8 с | 13 255 951 байт |

То есть предел, который я объявил часом раньше против «вошёл и завис», снял **два работавших плеча**.
Ошибка того же класса, что и предыдущая (§13.117): правило снимало плечо, не спросив, идёт ли работа.

**Темп стенда измерен.** 1800 с дают 76-90 ходов, то есть **~20-24 с на ход**; заказанные 150 ходов ≈
**60 минут** на плечо. Отсюда предел объявлен заново, ДО данных серии: **`STALL_CAP = 5400`** (90 минут) —
запас на весь заказанный прогон плюс треть. Значение выведено из измерения, а не подобрано.

**Что это даёт серии.** Пилотная пара показала главное: стенд отдаёт партию ОБОИМ плечам и держит её
десятки ходов, счёт считается (9.0 у обоих). Значит серия возможна; её цена — около часа на пару при
двух плечах, идущих параллельно (по записи обе шли ровно 1800.8 с, то есть одновременно), то есть
10 пар ≈ 10 часов непрерывного прогона. Это надо называть владельцу заранее.

**Про запись.** Строки плеч сохранили ходы и счёт (76/9.0 и 90/9.0) даже при снятии: числа берутся из
трассы, а не из выхода процесса. Но пометка `stalled` уводит такие строки из вердикта — поэтому серия
пойдёт только после пары, где плечи закрылись сами.
"""


def main() -> None:
    text = CAL.read_text(encoding="utf-8")
    if "### 13.118 Жёсткий предел" in text:
        print("раздел 13.118 уже записан")
    else:
        CAL.write_text(text.rstrip() + "\n" + SECTION.rstrip() + "\n", encoding="utf-8")
        print("раздел 13.118 записан | знаков:", len(CAL.read_text(encoding="utf-8")))


main()
