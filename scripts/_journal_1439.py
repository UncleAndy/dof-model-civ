"""13.139: mir ne igraet sam - partiya bez klienta stoit. Chistoe plecho B nevypolnimo."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"

SECTION = """
### 13.139 Мир не играет сам: партия без нашего клиента стоит. Чистое плечо B невыполнимо

**Проба плеча B** (`scripts/arm_b_ai_only.py`, слот 6301, `aifill 4`, `minp 1`): наш клиент создал партию,
уступил своё место встроенному ИИ командой `/aitoggle bai`, вышел, подождал 200 секунд, вернулся.

**Измерено:** ход на уходе — 1, ход после возвращения — 1. **Партия стоит.** Мир не играет сам: игре нужен
подключённый клиент, который двигает ход. Это то же самое явление, что и заморозок слота (§13.137), только
увиденное с другой стороны: ушедший клиент оставляет игру стоять, даже когда все места формально отданы ИИ.

**Что из этого следует:**

1. **Чистое плечо B** («за все места играет только встроенный ИИ, наших агентов нет вовсе») на этом стенде
   **невыполнимо**: без нашего клиента партия не движется, а клиент, лишённый места, хода не получает
   (§13.129/§13.133 — у наблюдателя нет пакета хода).
2. **Ближайшее выполнимое B** — встроенный ИИ на всех местах плюс **один наш клиент-хранитель времени**,
   который сам не принимает решений (политика бездействия). Тогда все содержательные места играет мир, а
   наш клиент только двигает ход. Это **примесь**, и её надо объявлять владельцу: в плече B одно место из N
   будет нашим-бездействующим, а не встроенным ИИ.
3. **Прямая дорога к чистому B** — починить вход наблюдателя в **общей** библиотеке клиента (там сейчас
   `assert (pplayer != None)`), чтобы клиент мог смотреть партию, не занимая места. Это решение владельца:
   правка общей библиотеки стенда.

**Побочное, к исправлению в оснастке:** список игроков из наблюдения читается пустым (форма наблюдения
иная, чем я предположил) — состав партии надо брать из `player_ctrl`, а не из среза наблюдения.
"""


def main() -> None:
    text = CAL.read_text(encoding="utf-8")
    if "### 13.139 Мир не играет сам" in text:
        print("раздел 13.139 уже записан")
    else:
        CAL.write_text(text.rstrip() + "\n" + SECTION.rstrip() + "\n", encoding="utf-8")
        print("раздел 13.139 записан | знаков:", len(CAL.read_text(encoding="utf-8")))


main()
