"""Итог опыта «разведка против без разведки» + проверка гипотезы «кого именно двигала оснастка».

Вердикт уже посчитан судьёй: A (разведка) медиана 2 против B (без разведки) 13.5, разности все
отрицательные, побед A 0 из 10 — «эффект не установлен» формально, а по направлению разведка
в текущем виде СТОИТ около 10 очков мира. Здесь это записывается и проверяется, не смещается ли
потеря не «разведкой», а тем, что оснастка уводила конкретных юнитов от дела.
"""
import glob
import json
import re
import statistics as st
from pathlib import Path

ROOT = Path("/home/hermes/projects/AI/DOF-MODEL-CIV")
rows = [json.loads(l) for l in (ROOT / "knowledge/ab_scout.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]
per: dict[int, dict] = {}
for r in rows:
    per.setdefault(int(r["pair"]), {})[r["arm"]] = r
diffs, med_a, med_b = [], [], []
for p in sorted(per):
    a, b = per[p].get("A"), per[p].get("B")
    if not (a and b):
        continue
    diffs.append(float(a["score"]) - float(b["score"]))
    med_a.append(float(a["score"]))
    med_b.append(float(b["score"]))
print(f"пар {len(diffs)}; медианы A {st.median(med_a):g} / B {st.median(med_b):g}; "
      f"медиана разностей {st.median(diffs):g}; разности {diffs}")

# Кого двигала оснастка и по сколько раз — из логов плеча A всех пар.
actors: dict[str, int] = {}
for log in sorted(glob.glob("/home/hermes/ab_ab*_A_92*.txt")):
    for m in re.finditer(r"разведка \(оснастка\): (goto_\d+) юнитом (\d+)", Path(log).read_text(encoding="utf-8", errors="ignore")):
        actors[m.group(2)] = actors.get(m.group(2), 0) + 1
print("шагов разведки по юнитам:", dict(sorted(actors.items(), key=lambda kv: -kv[1])))

# Что это за юниты: смотрим трассу первой пары — состав своих юнитов в её строках.
tr = sorted(glob.glob(str(ROOT / "knowledge/live_trace_9200_port6000_ab*.jsonl")))
kinds: dict[str, str] = {}
if tr:
    with open(tr[0], encoding="utf-8") as fh:
        for i, line in enumerate(fh):
            if i > 40:
                break
            rec = json.loads(line)
            for key in ("свои_юниты", "units", "сущности", "entities"):
                for e in (rec.get(key) or []):
                    if isinstance(e, dict) and e.get("eid") is not None:
                        kinds[str(e.get("eid"))] = str(e.get("вид") or e.get("kind") or "—")
            if kinds:
                break
print("виды двигавшихся юнитов (по трассе, если найдены):",
      {k: kinds[k] for k in actors if k in kinds} or "не найдено в этой трассе")

DOC = ROOT / "drafts/DOF_CALIBRATION.md"
ANCHOR = "## 14. Сверка веток `v2` и `v0.11` (2026-10-06)"
SECTION = f"""### 13.61 Вердикт опыта «разведка против без разведки»: разведка в текущем виде СТОИТ очки

**Протокол объявлен до данных:** 10 пар, сиды 9200–9209, по 150 ходов, плечо A — драйвер плюс оснастка
«шаг к нераскрытой клетке» (один шаг за ход, `V011_SCOUT=1`), плечо B — драйвер как есть; мера — счёт
мира; правило вердикта то же, что в §13.59. Оснастка помечена в прогоне как оснастка, не поведение
модели; без переменной `V011_SCOUT` прогон не меняется.

**Данные** (`knowledge/ab_scout.jsonl`, 20 прогонов, по строке на прогон):

| пара | A (разведка) | B (без разведки) | разность |
|---|---|---|---|
| 1 | 1 | 20 | −19 |
| 2 | 3 | 13 | −10 |
| 3 | 4 | 14 | −10 |
| 4 | 2 | 12 | −10 |
| 5 | 2 | 14 | −12 |
| 6 | 2 | 12 | −10 |
| 7 | 1 | 11 | −10 |
| 8 | 1 | 11 | −10 |
| 9 | 2 | 15 | −13 |
| 10 | 1 | 17 | −16 |

**Вердикт (по трём условиям): не установлен** — медиана разностей **−10** против порога `+2`; побед A
**0 из 10**, `p = 1.0000`. Но здесь формальная формулировка слабее правды: разности отрицательны во
**всех десяти** парах, а медианы расходятся втрое (A **2**, B **13.5**). Это не «эффекта нет» — это
**разведка в текущем виде стоит около десяти очков мира из тринадцати**.

**Как читать без сглаживания.** В `v2` отслеживаемое окно движения уже показывал нули на городе
(`city_grew 0`, `city_options_delta 0`, §13.60), и наш опыт это подтверждает с другой стороны: за 150
ходов шаг разведки не приносит счёту ничего, а стоит — потому что за ход у юнита **одно** действие, и
шаг разведки его занимает. Движение в нашей постановке не «дополнительная» деятельность, а **замена**
производительной.

**Гипотеза, которая объясняет размер потери (не проверена до конца, помечаю как гипотезу).** Оснастка
двигала тех, кто первым в меню, и могла уводить юнита из-под дела (работу у города, поселенца) — тогда
потеря объясняется не «разведкой», а срывом работы. Проверка не доведена: шаги по юнитам
**{dict(sorted(actors.items(), key=lambda kv: -kv[1]))}**, а вид этих юнитов по трассе
**{('установлен: ' + str({k: kinds[k] for k in actors if k in kinds})) if any(k in kinds for k in actors) else 'в первых строках трассы не найден — вопрос открыт'}**.

**Что из этого следует для пункта 7.2.** Цену разведки искать не надо: она измерена и отрицательна в
нынешней форме. Прежде чем что-либо объявлять в модели, нужен опыт, отделяющий «движение вообще» от
«срыва работы»: плечо A′ — разведка **только тогда, когда драйвер сам не выбрал действия** (приоритет
у дела, а не у движения), и третье плечо — движение по случайному направлению. Если и при приоритете
дела разведка стоит очков, вопрос закрыт: в этой игре у движения нет цены, и `goto_0 = 0.0000`
останется не дефектом, а выводом.

"""
text = DOC.read_text(encoding="utf-8")
if ANCHOR not in text:
    raise SystemExit("якорь §14 не найден")
