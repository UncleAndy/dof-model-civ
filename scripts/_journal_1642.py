"""13.342: канал несёт ЮНИТОВ (23/24), улучшения — 0/22; в обычной партии счёт путают завершения построек."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"
TITLE = "## 13.342."
BODY = """## 13.342. Канал несёт ЮНИТОВ; улучшения не проходят. Обычную партию путают завершения построек

### Две контрольные руки (постоянный приказ одним прибором, `DOF_FORCE_PROD`)

| приказ (постоянный) | род | пар «приказ ↔ очередь на след. ходу» | применено |
|---|---|---|---|
| `produce_Settlers` (юнит №0) | юнит | 24 | **23** (очередь `kind=6, value=68` = `Settlers`) |
| `produce_Barracks` (улучшение №3) | улучшение | 22 | **0** (очередь остаётся юнитом) |

Обе руки идут на одном стенде, одним прибором, в одном и том же виде партии. Разница между ними —
**род предмета**, и это единственное отличие, которое меняется вместе с исходом.

**Вывод:** клиентский канал ставит производство **юнитов** и **не ставит улучшения** — это ровно то,
что в скилле было записано ранее («our client channel can order unit production and nothing else»), и
чего §13.338 не различал. Меню мира называет `Barracks` строящимся (`маска МИРА: ['Barracks', 'Coinage',
'Settlers', 'Warriors']`), действие среды по нему годно (`годно=True`, `prod_kind=3`, `prod_value=3`) — и
приказ всё равно не доходит.

### Обычная партия (наши приказы выбором, 2×40 ходов, непрерывный след)

| заказали | что стало в очереди на следующем ходу | раз |
|---|---|---|
| `Warriors` | улучшение `67` (`Coinage`) | 14 |
| `Warriors` | `6/71` (`Warriors`) | 1 |
| `Warriors` | улучшение `3` (`Barracks`) | 1 |
| `Barracks` | `3/3` (`Barracks`) | 2 |
| `Barracks` | `6/71` (`Warriors`) | 1 |

Читать это как «наш приказ не применён» **нельзя**: пара «приказ ↔ очередь на следующем ходу» ломается
там, где город в тот же ход **завершил** постройку — тогда сервер сам выбирает следующий предмет
(`choose_build_target`, `cityturn.c:2330-2353`: список работ → повтор → совет), и в очереди оказывается
`Coinage` — та самая «конвертирующая» постройка, которая у него идёт запасным путём. Поэтому одиночные
пары в обычной партии смешивают два события: наш приказ и выбор сервера после завершения.

**Следствие для приёмки:** мерить канал можно только на приказах, не совпадающих с завершением
(например, сравнивая запас щитов: он падает только на завершении), а судить о выборе нашего агента — по
тому, что город строит **в среднем по партии**, а не по паре ходов. Прибор `DOF_FORCE_PROD` и
непрерывный след `[очередь-ход]` для этого уже есть.
"""

text = CAL.read_text(encoding="utf-8")
if TITLE in text:
    start = text.find(TITLE)
    end = text.find("\n## 13.", start + len(TITLE))
    text = (text[:start] + BODY.rstrip() + text[end:]) if end >= 0 else (text[:start] + BODY)
    print(f"Replaced {TITLE}")
else:
    text = text.rstrip() + "\n\n" + BODY
    print(f"Appended {TITLE}")
CAL.write_text(text, encoding="utf-8")
