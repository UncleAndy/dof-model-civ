TITLE = "## 13.348."
BODY = """## 13.348. Поселенец не доходит: правило видит его на СОСЕДНЕЙ клетке от той, где он стоит

### Перенесено (его миссия)

`daisettler.c:1029-1054` `dai_auto_settler_run`: у поселенца **задача с клеткой-целью**
(`AIUNIT_BUILD_CITY`, `punit->goto_tile`), он ведёт его туда, пока цель годна, и основывает город
**по прибытии** (`same_pos(unit_tile(punit), ptile)`). У нас цель пересчитывалась каждый ход, а в
цене площадки сидит дорога — отсюда качание (§13.347). Внесено: цель **держится** в `_FOUND_TARGET`
до прибытия, снимается при прибытии или недостижимости.

### Замер (`hold2`, 150 ходов) — цель ни разу не сработала, и вот почему

| что | значение |
|---|---|
| городов в конце | **1** |
| поселенец 105 (дамп, по ходам) | стоит на **(71,18)** с 2-го по 150-й ход — 148 ходов без движения |
| позиция того же поселенца по следу правила | **(72,17)** — соседняя клетка |
| строк «держу цель» | **0** |
| счёт / население / технологии | 18.0 против 118.7 (×6.6) / 3 против 41.3 (×13.8) / **7** против 31.7 (×4.5) |

Оба числа читаются из ОДНОГО поля (`obs["unit"][id]["x"], ["y"]`): правило берёт его в `act`,
дамп — после `env.step`. Расхождение устойчиво 148 ходов, значит **правило считает шаг от клетки,
которую поселенец уже покинул**: приказ «шаг к (71,18)» из (72,17) превращается в приказ встать на
клетку, где он и стоит, — цель достигнутой не считается, город не основывается, поселенец стоит.

Это же объясняет, почему перенос миссии не сработал: у нас «цель достигнута» проверяется по
**устаревшей** позиции, а у него — по `unit_tile(punit)` мира в момент хода.

### Следующий шаг (замер, а не догадка)

Напечатать в ОДНОМ ходу обе позиции поселенца (из `act` и из дампа после `env.step`) с номером
хода — и, если отставание подтвердится, вести поселенца по позиции ПОСЛЕ хода (или пересчитывать
шаг только когда позиция изменилась, как только цель перестала быть соседней). Проверка после
починки — города за 150 ходов, не одна партия.

**Отдельно:** из 150 ходов в этой партии счёт ×6.6 (было ×12), технологии ×4.5 (было ×9.9) —
улучшение есть, но города остаются единицей, и это по-прежнему главный разрыв.
"""

