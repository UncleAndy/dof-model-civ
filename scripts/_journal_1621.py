"""13.321: поправка к 13.320 — дефект двойного счёта есть, но «корнем разрыва» он не доказан."""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAL = ROOT / "drafts" / "DOF_CALIBRATION.md"
TITLE = "## 13.321. Поправка к §13.320: двойной счёт площадки измерен, но «корнем разрыва» не доказан"
BODY = """## 13.321. Поправка к §13.320: двойной счёт площадки измерен, но «корнем разрыва» не доказан

### Что я утверждал и почему это было слишком сильно

В §13.320 я назвал независимый набор ресурсов в `evaluate_site` **корнем** разрыва: дескать,
завышенные щиты заставляют агента ставить города на земле, где город не произведёт ничего. Доказательство
было взято с **города размера 4** — выросшего, а не с решения об основании. Это подмена: мера дефекта
взята там, где дефект заметен, а вывод сделан про путь, где она не проверялась.

### Что показал замер на живых площадках

Добавлена диагностика (только счёт, решений не меняет; `DOF_SITE_DEBUG=1`) — она печатает нашу
независимую оценку и совместную рядом. Прогон `dof_economic`, 30 ходов: **8226 оценок площадок**.

| размер при оценке | сколько |
|---|---|
| 1 | **8225** |
| 2 | 1 |

| завышение щитов | сколько |
|---|---|
| 0 | 4761 |
| +1 | **3237** |
| +2 | 228 |

То есть дефект **реален** (42 % оценок завышены, до +2 щитов) — но **оценки основания идут размером 1**,
а не 4. На размере 1 в набор входят центр и одна клетка, и завышение возникает лишь когда лучшая по
еде клетка не совпадает с лучшей по щитам; на размере 4 оно вчетверо больше (5 против 3 на нашем
городе), и именно там я его измерил.

**Чего замер НЕ показал:** что завышение меняет **выбор**. Чтобы это утверждать, надо сравнить
выбранную площадку со лучшей по совместной мере на одних и тех же кандидатах — этого я не делал.

### Состояние после поправки

* Дефект: **есть, измерен** (42 % оценок, +1…+2 щита). Совместная оценка добавлена в код
  (`joint_site_outputs`, поля `joint_*`, `shields_inflated`) со сторожем
  `tests/unit/test_site_eval_joint.py` (**7 passed**), но **решения по ней не принимаются** —
  независимая оценка по-прежнему решает.
* «Корень разрыва»: **не доказан**. Разрыв (один город, один юнит за 150 ходов) остаётся
  необъяснённым, и место ему я пока не нашёл.
* Следующий замер, чтобы вопрос закрылся: на каждом основании записывать выбранную площадку и
  лучшую по совместной мере среди тех же кандидатов. Если выбор не совпадает — дефект ведёт решение;
  если совпадает — дефект безвреден на этом пути, и искать надо в другом месте.

**Дисциплина, которая это поймала:** пороги и меры объявляются ДО данных, а неожиданный результат —
тоже результат. Здесь замер опроверг мою же формулировку, и это записано, а не спрятано.
"""

text = CAL.read_text(encoding="utf-8")
if TITLE in text:
    start = text.find(TITLE)
    end = text.find("\n## 13.", start + len(TITLE))
    text = (text[:start] + BODY.rstrip() + text[end:]) if end >= 0 else (text[:start] + BODY)
    print(f"Replaced {TITLE}")
else:
    text = text.rstrip() + "\n\n" + BODY
    print(f"Appended {TITLE}")
CAL.write_text(text, encoding="utf-8")
