"""Цена раскрытия: разрыв Дженсена по измеренному разбросу.

Содержание скрытой клетки модель уже считает средним по раскрытым
(`evaluate_site`, Axiom 5/7). Поэтому «ещё одна средняя клетка» выгоды не даёт —
и это не парадокс, а следствие самого правила. Остаётся **опция**: узнать, что
неизвестная клетка лучше (или хуже) среднего, и распорядиться этим.

Для максимизатора неопределённость поднимает ожидаемый максимум:

    E[max(v, V)] ≥ max(v, E[V]),   V — измеренное распределение ценностей

Разница (разрыв Дженсена) — и есть ценность одного раскрытия. Свободных
параметров нет: `V` берётся из фактического разброса ценностей клеток на карте.

Две шкалы, одна величина:

* `gap_options` — в опциях (для упорядочивания кандидатов);
* `gap_index`   — в единицах индекса `Σ ln DoF` (для решения): относительный
  прирост лучшей доступной возможности, `ln E[max] − ln max E`. Нужна потому, что
  поиск принимает только строгое улучшение ИНДЕКСА, и ход с нулевой дельтой
  отвергается — цена раскрытия обязана быть видна именно там.

Обе возвращают 0 при вырожденном распределении (все значения равны) — тогда
разглядывать нечего, и это честный ноль, а не отсутствие данных.
"""
from __future__ import annotations

import math

EPSILON = 1e-9


def gap_options(sample: list[float], best_known: float = 0.0) -> float:
    """Разрыв Дженсена в опциях: `E[max(v,V)] − max(v, E[V])`."""
    values = [float(v) for v in sample if v is not None]
    if not values:
        return 0.0
    best = float(best_known)
    mean_expected = sum(values) / len(values)
    drawn = sum(max(best, v) for v in values) / len(values)
    return max(0.0, drawn - max(best, mean_expected))


def gap_index(sample: list[float], best_known: float = 0.0,
              potential: float | None = None) -> float:
    """Ценность раскрытия В ШКАЛЕ ИНДЕКСА — там, где принимается решение.

    Считается ровно та величина, которой меряется всё остальное: индекс
    `Σ ln(DoF)`. Вера модели — среднее по видимым; розыгрыш — конкретная клетка.
    Тогда

        gap = E[ ln(max(V, 1)) ] − ln(max(mean(V), 1)),

    где `ln(max(x, 1))` — индекс одной живой сущности (живая сущность имеет хотя бы
    одну опцию). `best_known` — индекс лучшей опции, которую агент ДЕРЖИТ сейчас
    (логарифм, а не опции!), и он подставляется как нижняя граница в обе части:
    плохая новость не обесценивает то, что уже есть.

    `potential` — ОДНО возможное значение из неизвестного (измеренный разброс,
    §10.27.1). Оно входит в РОЗЫГРЫШ, но не в ВЕРУ: вера — это то, что мы считаем
    средним по видимому, а потенциал — то, что может открыться. Без такого
    разделения разрыв тождественно ноль в обычном случае: лучшая удерживаемая
    площадка и есть максимум выборки, поэтому ни один розыгрыш её не превышает, а
    если добавить потенциал ещё и в веру, вера поднимается выше реализованного
    среднего и разрыв снова обнуляется (измерено: 0.000 при опциях 0.270).

    Почему не в опциях (первая редакция формулы, отозвана): решение принимает
    поиск В ИНДЕКСЕ, и цена в опциях не проходила правило «строго больше нуля» —
    при пустой локальной окрестности агент не шёл в туман вообще. Здесь же скромная
    область получает цену: вера даёт индекс `ln 1 = 0` («средняя клетка бесполезна»),
    а редкая находка — положительный, и разница становится стимулом искать.
    """
    values = [float(v) for v in sample if v is not None]
    if not values:
        return 0.0
    best = max(float(best_known), 0.0)

    def value(x: float) -> float:
        return math.log(max(float(x), 1.0))

    drawn = [max(best, value(v)) for v in values]
    mean_expected = sum(drawn) / len(drawn)
    if potential is not None:
        mean_expected = ((sum(drawn) + max(best, value(float(potential))))
                         / (len(drawn) + 1))
    mean_believed = max(best, value(sum(values) / len(values)))
    return max(0.0, mean_expected - mean_believed)
