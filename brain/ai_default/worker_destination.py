"""Куда идти рабочему — перенос решения встроенного ИИ о цели рабочего (§13.451).

Зачем отдельный модуль. Диагностика §13.450 показала: цепочка работ исправна, но она рассматривает
ТУ клетку, на которой рабочий стоит. Если работы на ней нет, встроенный ИИ ведёт рабочего туда, где
она есть, а у нас такого решения не было вовсе — рабочий стоял и молчал (отправленных работ 0 при
живых юнитах-рабочих).

Правило взято из его кода, а не придумано: у него работу выбирает `best_impr` для клетки, а выигрыш
дисконтируется числом ходов работы (`amortize(total, delay)`, см. `worker_choice.amortize`). Поэтому
цель рабочего — клетка с наибольшим ДИСКОНТИРОВАННЫМ выигрышем работы, доступной рабочему сейчас.

Что модуль НЕ делает: он не выдумывает ценности. Если для клетки нет ни одного варианта работы по
правилам мира, клетка не рассматривается — «нет данных» не превращается в «работать здесь».
"""

from __future__ import annotations

from typing import Callable, Iterable, Optional

__all__ = ["best_work_tile"]


def best_work_tile(
    *,
    worker_pos: tuple[int, int],
    tiles: Iterable[tuple[int, int]],
    options_for: Callable[[tuple[int, int]], Optional[dict]],
    gain_of: Callable[[dict], float],
    in_use: Iterable[tuple[int, int]] = (),
    radius: int = 6,
) -> Optional[tuple[int, int]]:
    """Клетка, на которую рабочему выгоднее всего идти.

    Параметры нарочно сделаны функциями, а не данными: `options_for` возвращает варианты работ для
    клетки РОВНО тем же правилом, что и на месте (из правил мира), а `gain_of` считает выигрыш
    выбранного варианта. Так решение о цели и решение о работе не могут разойтись — у него в коде
    это тоже одна и та же оценка.

    `in_use` — клетки, которые уже обрабатываются городами: они в приоритете, потому что их прирост
    город получает сразу. Ход не оценивается: сравнение идёт по выигрышу работы, как у него.
    """
    best: Optional[tuple[int, int]] = None
    best_gain = 0.0
    bx, by = worker_pos
    used = set(in_use)
    for (tx, ty) in tiles:
        if (tx, ty) == (bx, by):
            continue
        if abs(tx - bx) > radius or abs(ty - by) > radius:
            continue
        opts = options_for((tx, ty))
        if not opts:
            continue
        gain = float(gain_of(opts))
        if gain <= 0.0:
            continue
        # Клетка в обработке города весит больше: её прирост достаётся городу сразу, а не потом.
        if (tx, ty) in used:
            gain *= 1.0 + 1e-6
        if gain > best_gain:
            best_gain = gain
            best = (tx, ty)
    return best
