"""Дуэльная статистика: парные разницы и вердикт по зеркалу.

Дуэль отвечает на сравнительный вопрос («какая политика играет лучше в ОДНОМ
мире»), поэтому единица наблюдения — игра, а не игрок: разница считается внутри
игры, и карта из неё вычитается сама.

Зеркало (одна политика против себя) — контроль самой конструкции. При
последовательных ходах (`phasemode player`) и несимметричном старте дизайн
обязан давать НЕНУЛЕВУЮ разницу, даже когда обе стороны — одна и та же политика.
Поэтому пороги вердикта заданы здесь, в коде, и не двигаются под результат.
"""
from __future__ import annotations

from .stats import ci95, mean

#: Меньше этого числа пригодных игр — вердикта нет. Разница по двум играм это не
#: свойство дизайна, а шум конкретных карт.
MIRROR_MIN_GAMES = 3


def paired_summary(diffs: list[float]) -> dict:
    """Средняя парная разница и её 95% доверительный интервал."""
    if not diffs:
        return {'n': 0, 'mean': 0.0, 'ci': [0.0, 0.0]}
    lo, hi = ci95(diffs)
    return {'n': len(diffs), 'mean': mean(diffs), 'ci': [lo, hi]}


def mirror_verdict(diffs: list[float], min_games: int = MIRROR_MIN_GAMES) -> dict:
    """Годится ли дизайн дуэли: разница «политика против себя» должна быть нулём.

    Возвращает решение СЧЁТОМ, а не суждением:

    * пригодных игр меньше порога → вердикта нет («мало данных»);
    * ноль внутри интервала → зеркало чистое, дизайн годится;
    * ноль вне интервала → дизайн смещён (порядок ходов/асимметрия старта), и
      результаты любых дуэлей на нём не значат ничего.
    """
    s = paired_summary(diffs)
    if s['n'] < min_games:
        return {'ok': False, 'verdict': 'no_data', 'summary': s,
                'reason': (f'пригодных игр {s["n"]} < {min_games}: вердикта нет '
                           f'(это «мало данных», а не «дизайн чист»)')}
    lo, hi = s['ci']
    if lo <= 0.0 <= hi:
        return {'ok': True, 'verdict': 'clean', 'summary': s,
                'reason': (f'разница неотличима от нуля: {s["mean"]:+.2f}, '
                           f'95% CI [{lo:+.2f}, {hi:+.2f}], игр {s["n"]}')}
    return {'ok': False, 'verdict': 'biased', 'summary': s,
            'reason': (f'разница систематическая: {s["mean"]:+.2f}, '
                       f'95% CI [{lo:+.2f}, {hi:+.2f}], игр {s["n"]} — ноль вне '
                       f'интервала, дизайн смещён (порядок ходов/старт)')}


def ab_verdict(diffs: list[float], min_games: int = MIRROR_MIN_GAMES) -> dict:
    """Вердикт очной ставки: различаются ли варианты X и Y.

    `diffs` — парные разницы (X минус Y) по играм, причём сторона неважна: если
    между играми сторона переставляется, позиционное преимущество вычитается
    вместе с картой. Разница «нет различия» — это тоже результат, и он не
    выдаётся за «эффекта нет»: интервал сообщает, какой эффект данные исключают.
    """
    s = paired_summary(diffs)
    if s['n'] < min_games:
        return {'ok': False, 'verdict': 'no_data', 'summary': s,
                'reason': (f'пригодных игр {s["n"]} < {min_games}: вердикта нет '
                           f'(«мало данных», а не «различий нет»)')}
    lo, hi = s['ci']
    if lo <= 0.0 <= hi:
        return {'ok': True, 'verdict': 'no_difference', 'summary': s,
                'reason': (f'различие не показано: {s["mean"]:+.2f}, '
                           f'95% CI [{lo:+.2f}, {hi:+.2f}], игр {s["n"]} — ноль '
                           f'внутри интервала')}
    who = 'X' if s['mean'] > 0 else 'Y'
    return {'ok': True, 'verdict': 'difference', 'summary': s,
            'reason': (f'различие есть и в пользу {who}: {s["mean"]:+.2f}, '
                       f'95% CI [{lo:+.2f}, {hi:+.2f}], игр {s["n"]}')}
